#!/usr/bin/env node
// Writes the TypeScript declarations of Control Studio's engine messages from the JSON Schema files that
// `cargo run -p trust-control --bin export-schema -- <schema-folder>` writes: one `<Type>.ts` for each `<Type>.json`.
//
// Usage: node scripts/generate-control-studio-types.js <schema-folder> [<output-folder>]
// The output folder defaults to src/controlStudio/generated. Each run replaces the `.ts` files already there.
"use strict";

const fs = require("fs");
const path = require("path");

const extensionRoot = path.resolve(__dirname, "..");
const defaultOutputFolder = path.join(extensionRoot, "src", "controlStudio", "generated");

const banner = [
  "/**",
  " * Generated by editors/vscode/scripts/generate-control-studio-types.js from the engine's JSON Schema",
  " * (cargo run -p trust-control --bin export-schema). Do not edit this file.",
  " */",
].join("\n");

async function main() {
  const [schemaArgument, outputArgument] = process.argv.slice(2);
  if (!schemaArgument) {
    console.error("usage: node scripts/generate-control-studio-types.js <schema-folder> [<output-folder>]");
    process.exit(2);
  }
  const schemaFolder = path.resolve(schemaArgument);
  const outputFolder = path.resolve(outputArgument ?? defaultOutputFolder);
  const schemaFiles = fs
    .readdirSync(schemaFolder)
    .filter((name) => name.endsWith(".json"))
    .sort();
  if (schemaFiles.length === 0) {
    console.error(`no JSON Schema files in ${schemaFolder}`);
    process.exit(1);
  }

  const { compile } = await import("json-schema-to-typescript");
  fs.mkdirSync(outputFolder, { recursive: true });
  for (const stale of fs.readdirSync(outputFolder).filter((name) => name.endsWith(".ts"))) {
    fs.unlinkSync(path.join(outputFolder, stale));
  }
  for (const file of schemaFiles) {
    const name = path.basename(file, ".json");
    const schema = JSON.parse(fs.readFileSync(path.join(schemaFolder, file), "utf8"));
    const declaration = await compile(schema, name, { bannerComment: banner });
    fs.writeFileSync(path.join(outputFolder, `${name}.ts`), declaration);
  }
  console.log(`wrote ${schemaFiles.length} declaration files to ${outputFolder}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
