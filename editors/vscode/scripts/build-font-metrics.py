#!/usr/bin/env python3
"""Writes the HMI drawing's text widths from the font it ships (specification 39, §14.2): the
advance width of every letter the table covers, for each weight the drawing uses, at the font's
text optical size. The drawing measures every text with them, so its layout matches the screen.

Needs fontTools with brotli (`pip install fonttools brotli`). Run after the font changes:
    python3 editors/vscode/scripts/build-font-metrics.py
A VS Code test fails while the table belongs to another font.
"""

import hashlib
from pathlib import Path

from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT.parents[1] / "crates" / "trust-runtime" / "src" / "web" / "ui" / "assets" / "fonts" / "InterVariable.woff2"
OUT = ROOT / "src" / "hmiBuilder" / "drawing" / "fontMetrics.ts"
WEIGHTS = [400, 500, 550, 600, 650, 700, 800]
# Latin, Latin-1, Latin Extended-A, Greek, Cyrillic, and the punctuation and signs units use.
RANGES = [(0x20, 0x7E), (0xA0, 0x17F), (0x370, 0x3FF), (0x400, 0x45F), (0x2010, 0x2027),
          (0x2030, 0x203A), (0x20AC, 0x20AC), (0x2190, 0x2193), (0x2212, 0x2212), (0x2264, 0x2265)]


def base36(value):
    digits = "0123456789abcdefghijklmnopqrstuvwxyz"
    text = ""
    while True:
        value, rest = divmod(value, 36)
        text = digits[rest] + text
        if value == 0:
            return text.rjust(3, "0")


def main():
    data = FONT.read_bytes()
    font = TTFont(FONT)
    units = font["head"].unitsPerEm
    cmap = font.getBestCmap()
    chars = [code for start, end in RANGES for code in range(start, end + 1) if code in cmap]
    widths = {}
    for weight in WEIGHTS:
        instance = instancer.instantiateVariableFont(TTFont(FONT), {"wght": weight, "opsz": 14})
        hmtx, names = instance["hmtx"], instance.getBestCmap()
        widths[weight] = "".join(base36(hmtx[names[code]][0]) for code in chars)
    text = "".join(chr(code) for code in chars)
    escaped = text.replace("\\", "\\\\").replace('"', '\\"')
    lines = [
        "// Generated by `editors/vscode/scripts/build-font-metrics.py` from the HMI's font; do not",
        "// edit. Specification 39, §14.2: the advance widths of InterVariable.woff2 at optical size",
        "// 14, three base-36 digits a letter, for each weight the drawing uses.",
        "",
        f'export const FONT_SHA256 = "{hashlib.sha256(data).hexdigest()}";',
        f"export const FONT_UNITS = {units};",
        f'export const FONT_CHARS = "{escaped}";',
        "export const FONT_WIDTHS: Record<number, string> = {",
        *[f'  {weight}: "{widths[weight]}",' for weight in WEIGHTS],
        "};",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{OUT.relative_to(ROOT)}: {len(chars)} letters, {len(WEIGHTS)} weights")


main()
