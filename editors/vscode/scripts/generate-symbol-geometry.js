#!/usr/bin/env node
// Writes the drawing's module of the shipped symbols' geometry (src/hmiBuilder/drawing/symbols/geometry.ts) from the runtime's table
// (crates/trust-runtime/src/hmi/symbol_geometry.json; specification 39, §6 item 1, §14.2), so that the drawing and the language
// server meet the same ports. With `--check` it writes nothing and fails when the module is not the one the table gives.

const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const table = path.resolve(root, "../../crates/trust-runtime/src/hmi/symbol_geometry.json");
const target = path.join(root, "src/hmiBuilder/drawing/symbols/geometry.ts");

function moduleText() {
  const { format, labelHeight, shapes, symbols } = JSON.parse(fs.readFileSync(table, "utf8"));
  if (format !== 1) throw new Error(`symbol_geometry.json has format ${format}; this generator reads format 1`);
  const entries = Object.entries(symbols).map(([type, shape]) => {
    const geometry = shapes[shape];
    if (!geometry) throw new Error(`the symbol ${type} names the unknown shape ${shape}`);
    const ports = geometry.ports
      .map((port) => `${JSON.stringify(port.name)}: { at: [${port.at[0]}, ${port.at[1]}], direction: ${JSON.stringify(port.direction)} }`)
      .join(", ");
    const label = geometry.label ? `, label: ${JSON.stringify(geometry.label)}` : "";
    return `  ${JSON.stringify(type)}: { size: [${geometry.size[0]}, ${geometry.size[1]}]${label}, ports: { ${ports} } },`;
  });
  return `// Generated by editors/vscode/scripts/generate-symbol-geometry.js from the runtime's table of the shipped symbols' geometry
// (crates/trust-runtime/src/hmi/symbol_geometry.json; specification 39, §6 item 1, §14.2). Do not edit this file: change the table,
// then run \`npm run generate:symbol-geometry\`.

/** A connection point (§6): where a pipe meets the symbol, and the way the pipe leaves it. */
export interface SymbolPort {
  at: [number, number];
  direction: "left" | "right" | "up" | "down";
}

/** Where a symbol's tag and state word stand: under it, or beside it, as an instrument's do. */
export type SymbolLabel = "under" | "beside";

/** A shipped symbol's design size in pixels without its label, where its label stands (under it when not given), and its ports. */
export interface SymbolGeometry {
  size: [number, number];
  label?: SymbolLabel;
  ports: Record<string, SymbolPort>;
}

/** The room the label takes under a symbol: the tag and the state word, each 14 px (§14.2). */
export const LABEL_HEIGHT = ${labelHeight};

/** Each shipped symbol's geometry, by its type. */
export const SYMBOL_GEOMETRY: Readonly<Record<string, SymbolGeometry>> = {
${entries.join("\n")}
};
`;
}

/** The module as the HMI's formatter writes it (`npm run format:hmi`), so that the format check holds for it too. */
async function formatted() {
  const prettier = require("prettier");
  const options = (await prettier.resolveConfig(target)) ?? {};
  return prettier.format(moduleText(), { ...options, filepath: target });
}

formatted().then(
  (text) => {
    if (process.argv.includes("--check")) {
      const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
      if (current !== text) {
        console.error(`${path.relative(root, target)} is not the module the table gives: run npm run generate:symbol-geometry`);
        process.exit(1);
      }
    } else {
      fs.writeFileSync(target, text);
    }
  },
  (error) => {
    console.error(error.message);
    process.exit(1);
  },
);
