#[test]
fn the_scalar_adapter_reads_the_dead_time_form_and_its_output_state() {
    // [4]/[2, 1] is 2/(s + 0.5) once normalised: gain 2/0.5 = 4 and time constant 1/0.5 = 2; the
    // output state is c·x₀ = 2·18 = 36.
    let first_order = TransferFunction::new(vec![4.0], vec![2.0, 1.0]).expect("a valid function");
    assert!(is_exact_scalar_delay(&first_order));
    let adapter = scalar_delay_adapter(&first_order, 1.5, 18.0).expect("first-order domain");
    assert_eq!(
        adapter.form,
        ScalarDelayForm::FirstOrderDeadTime {
            gain: 4.0,
            time_constant_seconds: 2.0
        }
    );
    assert_eq!(adapter.dead_time_seconds, 1.5);
    assert!((adapter.initial_output_state - 36.0).abs() <= 1e-12);

    // [4]/[2, 0]: an integrator with gain 2; the output state is 2·0.5 = 1.
    let integrator = TransferFunction::new(vec![4.0], vec![2.0, 0.0]).expect("a valid function");
    let adapter = scalar_delay_adapter(&integrator, 0.13, 0.5).expect("integrator domain");
    assert_eq!(
        adapter.form,
        ScalarDelayForm::IntegratorDeadTime { gain: 2.0 }
    );
    assert!((adapter.initial_output_state - 1.0).abs() <= 1e-12);

    let second_order = TransferFunction::new(vec![4.0], vec![2.0, 1.0, 0.0]).expect("valid");
    assert!(!is_exact_scalar_delay(&second_order));
    assert_eq!(
        scalar_delay_adapter(&second_order, 1.0, 0.0),
        Err(SimulationError::NotFirstOrderScalar)
    );
}
