/// ADS symbol handle-by-name index group.
pub const ADSIGRP_SYM_HNDBYNAME: u32 = 0xF003;
/// ADS symbol value-by-name index group.
pub const ADSIGRP_SYM_VALBYNAME: u32 = 0xF004;
