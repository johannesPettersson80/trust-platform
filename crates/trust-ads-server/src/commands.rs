pub const ADSIGRP_SUMUP_READ_EX: u32 = 0xF083;

/// ADS notification mode: cyclic samples generated by the server.
pub const ADSTRANS_SERVERCYCLE: u32 = 3;
/// ADS notification mode: samples generated by the server when value bytes change.
pub const ADSTRANS_SERVERONCHA: u32 = 4;

const ADSSTATE_RUN: u16 = 5;
const DEFAULT_MAX_HANDLES_PER_CLIENT: usize = 4096;

/// Device info returned by ADS `ReadDeviceInfo`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct DeviceInfo {
    /// Major version byte.
    pub major_version: u8,
    /// Minor version byte.
    pub minor_version: u8,
    /// Build number.
    pub build: u16,
    /// Device name, truncated/padded to 16 bytes on the wire.
    pub name: String,
}

impl Default for DeviceInfo {
    fn default() -> Self {
        Self {
            major_version: 1,
            minor_version: 0,
            build: 0,
            name: "truST".to_string(),
        }
    }
}

/// ADS device state returned by ADS `ReadState`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct AdsDeviceState {
    /// ADS state value.
    pub ads_state: u16,
    /// Device-specific state.
    pub device_state: u16,
}

impl Default for AdsDeviceState {
    fn default() -> Self {
        Self {
            ads_state: ADSSTATE_RUN,
            device_state: 0,
        }
    }
}

/// One ADS notification sample carried by a `DeviceNotification` push.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct NotificationSample {
    /// ADS notification handle returned by `AddDeviceNotification`.
    pub handle: u32,
    /// Raw ADS value bytes for this sample.
    pub data: Vec<u8>,
}

impl NotificationSample {
    /// Creates a notification sample.
    #[must_use]
    pub fn new(handle: u32, data: impl Into<Vec<u8>>) -> Self {
        Self {
            handle,
            data: data.into(),
        }
    }

    /// Creates an invalidated-handle notification with zero data bytes.
    #[must_use]
    pub fn invalidated(handle: u32) -> Self {
        Self {
            handle,
            data: Vec::new(),
        }
    }
}

/// One ADS notification stamp grouping samples under one FILETIME timestamp.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct NotificationStamp {
    /// Windows FILETIME timestamp: 100 ns ticks since 1601-01-01 UTC.
    pub timestamp_filetime: u64,
    /// Samples delivered for this timestamp.
    pub samples: Vec<NotificationSample>,
}

impl NotificationStamp {
    /// Creates a notification stamp.
    #[must_use]
    pub fn new(timestamp_filetime: u64, samples: Vec<NotificationSample>) -> Self {
        Self {
            timestamp_filetime,
            samples,
        }
    }
}

/// Client endpoint that receives an active ADS notification registration.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub struct NotificationReceiver {
    /// Target AMS Net ID for unsolicited `DeviceNotification` frames.
    pub net_id: AmsNetIdBytes,
    /// Target ADS port for unsolicited `DeviceNotification` frames.
    pub port: u16,
}

/// Trait-backed command execution context.
pub struct CommandContext<'a> {
    /// Current ADS client identity.
    pub client: &'a ClientId,
    /// Symbol table provider.
    pub symbols: &'a dyn SymbolSource,
    /// Value reader.
    pub values: &'a dyn ValueIo,
    /// Runtime write port.
    pub writes: &'a dyn RuntimeWritePort,
    /// Client allowlist policy.
    pub policy: &'a dyn ClientPolicy,
    /// Audit sink.
    pub audit: &'a dyn AuditSink,
    /// Clock.
    pub clock: &'a dyn Clock,
    /// Device info response fields.
    pub device_info: DeviceInfo,
    /// ADS state response fields.
    pub device_state: AdsDeviceState,
    /// Logical ADS runtime port served by this command context.
    pub ads_port: u16,
    /// Receiver endpoint for notification registrations created by this command.
    pub notification_receiver: Option<NotificationReceiver>,
}

impl<'a> CommandContext<'a> {
    /// Creates a command context with default device metadata.
    #[must_use]
    pub fn new(
        client: &'a ClientId,
        symbols: &'a dyn SymbolSource,
        values: &'a dyn ValueIo,
        writes: &'a dyn RuntimeWritePort,
        policy: &'a dyn ClientPolicy,
        audit: &'a dyn AuditSink,
        clock: &'a dyn Clock,
    ) -> Self {
        Self {
            client,
            symbols,
            values,
            writes,
            policy,
            audit,
            clock,
            device_info: DeviceInfo::default(),
            device_state: AdsDeviceState::default(),
            ads_port: 851,
            notification_receiver: None,
        }
    }

    /// Returns this context with an ADS notification receiver endpoint.
    #[must_use]
    pub fn with_notification_receiver(mut self, receiver: NotificationReceiver) -> Self {
        self.notification_receiver = Some(receiver);
        self
    }
}

