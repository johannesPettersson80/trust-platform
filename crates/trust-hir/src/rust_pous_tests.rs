//! Rust POUs are known by `{attribute 'rust'}` and keep specification 48's rules for their
//! declarations (RU-23, RU-34).

use trust_syntax::parser::parse;
use trust_syntax::syntax::{SyntaxKind, SyntaxNode};

use super::{is_rust_pou, rust_pou_errors};

/// RU-23's generated declaration of FILTER_EMA.
const FILTER_EMA: &str = "(* GENERATED by trust-runtime from rust/src/filter.rs - do not edit *)
{attribute 'rust'}
FUNCTION_BLOCK FILTER_EMA
VAR_INPUT
    x : LREAL;
    alpha : LREAL := 0.1;
END_VAR
VAR_OUTPUT
    y : LREAL;
END_VAR
VAR
    primed : BOOL;
END_VAR
END_FUNCTION_BLOCK
";

fn root(text: &str) -> SyntaxNode {
    parse(text).syntax()
}

fn first(text: &str, kind: SyntaxKind) -> SyntaxNode {
    root(text)
        .descendants()
        .find(|node| node.kind() == kind)
        .expect("the declaration")
}

fn errors(text: &str) -> Vec<String> {
    rust_pou_errors(&root(text))
        .into_iter()
        .map(|(_, message)| message)
        .collect()
}

#[test]
fn a_generated_declaration_is_a_rust_pou_that_keeps_the_rules() {
    // Catches the mark read from another declaration or missed: the pragma before the keyword marks
    // the function block, function or program, and RU-23's generated declaration breaks no rule.
    assert!(is_rust_pou(&first(FILTER_EMA, SyntaxKind::FunctionBlock)));
    assert_eq!(errors(FILTER_EMA), Vec::<String>::new());
    let function = "{attribute 'rust'}\nFUNCTION MAX_LIMITED : DINT\nVAR_INPUT\n    a : DINT;\nEND_VAR\nEND_FUNCTION\n";
    assert!(is_rust_pou(&first(function, SyntaxKind::Function)));
    let program = "{attribute 'rust'}\nPROGRAM AXIS_CONTROLLER\nVAR_INPUT\n    x : LREAL;\nEND_VAR\nEND_PROGRAM\n";
    assert!(is_rust_pou(&first(program, SyntaxKind::Program)));
    let namespaced = "NAMESPACE Motion\n{attribute 'rust'}\nFUNCTION_BLOCK AXIS\nEND_FUNCTION_BLOCK\nEND_NAMESPACE\n";
    assert!(is_rust_pou(&first(namespaced, SyntaxKind::FunctionBlock)));
    assert_eq!(errors(namespaced), Vec::<String>::new());
    for text in [
        "FUNCTION_BLOCK PLAIN\nEND_FUNCTION_BLOCK\n",
        "{attribute 'hide'}\nFUNCTION_BLOCK PLAIN\nEND_FUNCTION_BLOCK\n",
    ] {
        assert!(
            !is_rust_pou(&first(text, SyntaxKind::FunctionBlock)),
            "{text}"
        );
    }
    // A Structured Text POU after a Rust one is no Rust POU: the mark is the pragma before each.
    let both = format!("{FILTER_EMA}FUNCTION_BLOCK PLAIN\nEND_FUNCTION_BLOCK\n");
    let marks: Vec<bool> = root(&both)
        .descendants()
        .filter(|node| node.kind() == SyntaxKind::FunctionBlock)
        .map(|node| is_rust_pou(&node))
        .collect();
    assert_eq!(marks, [true, false]);
}

#[test]
fn a_statement_in_a_rust_pou_is_refused() {
    // RU-23: a Rust POU's body is its Rust item; a statement in its declaration would never run.
    for text in [
        "{attribute 'rust'}\nFUNCTION_BLOCK F\nVAR_INPUT\n    x : INT;\nEND_VAR\nx := 1;\nEND_FUNCTION_BLOCK\n",
        "{attribute 'rust'}\nFUNCTION F : INT\nF := 1;\nEND_FUNCTION\n",
        "{attribute 'rust'}\nPROGRAM P\nVAR\n    x : INT;\nEND_VAR\nx := 1;\nEND_PROGRAM\n",
        "{attribute 'rust'}\nFUNCTION_BLOCK F\nMETHOD PUBLIC M : INT\nM := 1;\nEND_METHOD\nEND_FUNCTION_BLOCK\n",
    ] {
        let found = errors(text);
        assert_eq!(found.len(), 1, "{text}: {found:?}");
        assert!(found[0].contains("holds no statements"), "{text}: {found:?}");
    }
    // The same statements in a Structured Text POU are its body.
    assert_eq!(
        errors("FUNCTION F : INT\nF := 1;\nEND_FUNCTION\n"),
        Vec::<String>::new()
    );
}

#[test]
fn a_rust_pou_has_no_actions_properties_or_base() {
    // RU-34: a Rust function block extends nothing, and has methods instead of actions and
    // properties.
    let cases = [
        (
            "{attribute 'rust'}\nFUNCTION_BLOCK F EXTENDS BASE\nEND_FUNCTION_BLOCK\n",
            "extends no function block",
        ),
        (
            "{attribute 'rust'}\nFUNCTION_BLOCK F\nACTION Reset:\nEND_ACTION\nEND_FUNCTION_BLOCK\n",
            "no actions or properties",
        ),
        (
            "{attribute 'rust'}\nFUNCTION_BLOCK F\nPROPERTY Level : INT\nGET\nEND_GET\nEND_PROPERTY\nEND_FUNCTION_BLOCK\n",
            "no actions or properties",
        ),
    ];
    for (text, expected) in cases {
        let found = errors(text);
        assert!(
            found.iter().any(|message| message.contains(expected)),
            "{text}: {found:?}"
        );
    }
}

#[test]
fn the_attribute_on_another_declaration_is_refused() {
    // Catches `{attribute 'rust'}` that marks nothing a Rust item can be: a type, a class, an
    // interface or a variable list has no Rust body.
    for text in [
        "{attribute 'rust'}\nTYPE\n    T : STRUCT\n        a : INT;\n    END_STRUCT;\nEND_TYPE\n",
        "{attribute 'rust'}\nCLASS C\nEND_CLASS\n",
        "{attribute 'rust'}\nINTERFACE I\nEND_INTERFACE\n",
        "PROGRAM P\n{attribute 'rust'}\nVAR\n    x : INT;\nEND_VAR\nEND_PROGRAM\n",
    ] {
        let found = errors(text);
        assert_eq!(found.len(), 1, "{text}: {found:?}");
        assert!(
            found[0].contains("marks a function, function block or program"),
            "{text}: {found:?}"
        );
    }
}

#[test]
fn a_rust_blocks_method_has_its_result_from_rust() {
    // RU-32: a Rust function block's method is its Rust method, whose result its Rust code gives,
    // so its declaration without statements is no missing return value (E206), as a Rust
    // function's is not; a Structured Text block's method without one is. Catches the check
    // applied to a Rust method, or skipped for Structured Text's.
    use crate::db::{Database, FileId, SemanticDatabase, SourceDatabase};
    let missing = |text: String| {
        let mut database = Database::new();
        database.set_source_text(FileId(0), text);
        database
            .diagnostics(FileId(0))
            .iter()
            .any(|diagnostic| diagnostic.code == crate::diagnostics::DiagnosticCode::MissingReturn)
    };
    let block =
        "FUNCTION_BLOCK AXIS\nMETHOD PUBLIC jog : LREAL\nVAR_INPUT\n    distance : LREAL;\n\
                 END_VAR\nEND_METHOD\nEND_FUNCTION_BLOCK\n";
    assert!(!missing(format!("{{attribute 'rust'}}\n{block}")));
    assert!(missing(block.to_string()));
}
