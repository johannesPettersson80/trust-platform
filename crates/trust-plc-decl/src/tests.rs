#[test]
fn bit_strings_characters_and_durations_are_declared_with_iec_literals() {
    // RU-25 and RU-26: `Byte` to `Lword`, `Char`, `WChar`, `Time` and `LTime` are BYTE to LWORD,
    // CHAR, WCHAR, TIME and LTIME, and their initial values are IEC literals (IEC §6.3.2 to
    // §6.3.4): a bit string in hexadecimal at its width, a character quoted, a duration in units
    // from the largest. Catches a type declared as an integer, which ST would let a program add to.
    let item: ItemStruct = parse_quote! {
        #[budget("1us")]
        pub struct Typed {
            #[init(0x0F)] a: Byte,
            #[init(0xBEEF)] b: Word,
            #[init(1)] c: Dword,
            d: Lword,
            #[init('A')] e: Char,
            #[init(b'\xE9')] f: Char,
            #[init('é')] g: WChar,
            #[init("T#1.5s")] h: Time,
            #[init("T#-2h")] i: LTime,
            #[init("t#1d2h3m4s5ms6us7ns")] j: Time,
            #[init("T#0ms")] k: Time,
            #[init('$')] l: Char,
        }
    };
    let pou = function_block(args("name = \"TYPED\""), &item).unwrap();
    let declared: Vec<String> = pou
        .variables
        .iter()
        .map(|variable| match &variable.init {
            Some(init) => format!(
                "{} : {} := {}",
                variable.name,
                variable.ty.iec(),
                init.structured_text()
            ),
            None => format!("{} : {}", variable.name, variable.ty.iec()),
        })
        .collect();
    assert_eq!(
        declared,
        [
            "a : BYTE := 16#0F",
            "b : WORD := 16#BEEF",
            "c : DWORD := 16#00000001",
            "d : LWORD",
            "e : CHAR := 'A'",
            "f : CHAR := '$E9'",
            "g : WCHAR := \"$00E9\"",
            "h : TIME := T#1s500ms",
            "i : LTIME := LTIME#-2h",
            "j : TIME := T#1d2h3m4s5ms6us7ns",
            "k : TIME := T#0s",
            "l : CHAR := '$24'",
        ]
    );
    assert_eq!(
        pou.variables[7].init,
        Some(Value::Duration {
            long: false,
            nanos: 1_500_000_000
        })
    );
}

#[test]
fn dates_and_times_of_day_are_declared_with_iec_literals() {
    // RU-25 and RU-26: `Date` to `Ldt` are DATE to LDT, and their initial values are IEC literals
    // of their kind, short or long (IEC §6.3.5, Table 9), declared with the type's own prefix; a
    // variable without one starts at its type's default. Catches a date declared as an integer, a
    // long form declared with a short prefix, and a fraction's trailing zero kept.
    let item: ItemStruct = parse_quote! {
        #[budget("1us")]
        pub struct Dated {
            #[init("D#2024-02-29")] a: Date,
            #[init("LD#2024-02-29")] b: LDate,
            #[init("TIME_OF_DAY#12:30:15.250")] c: Tod,
            #[init("TOD#12:00:00.000000001")] d: LTod,
            #[init("DT#2024-02-29-12:30:15")] e: Dt,
            #[init("LDT#2024-02-29-12:30:15.5")] f: Ldt,
            g: Date,
        }
    };
    let pou = function_block(args("name = \"DATED\""), &item).unwrap();
    let declared: Vec<String> = pou
        .variables
        .iter()
        .map(|variable| match &variable.init {
            Some(init) => format!(
                "{} : {} := {}",
                variable.name,
                variable.ty.iec(),
                init.structured_text()
            ),
            None => format!("{} : {}", variable.name, variable.ty.iec()),
        })
        .collect();
    assert_eq!(
        declared,
        [
            "a : DATE := DATE#2024-02-29",
            "b : LDATE := LDATE#2024-02-29",
            "c : TOD := TOD#12:30:15.25",
            "d : LTOD := LTOD#12:00:00.000000001",
            "e : DT := DT#2024-02-29-12:30:15",
            "f : LDT := LDT#2024-02-29-12:30:15.5",
            "g : DATE",
        ]
    );
    // 2024-02-29 is day 19,782 after 1970-01-01: 1,709,164,800,000 ms.
    assert_eq!(
        pou.variables[0].init,
        Some(Value::Instant {
            ty: Elementary::Date,
            value: 1_709_164_800_000
        })
    );
}

