#[test]
fn an_enumeration_is_declared_as_a_closed_enumeration_with_its_values() {
    // RU-25: a `#[trust_enum]` enum is a closed enumeration of Structured Text (specification 02
    // §3.1) with its variants' names and values, inside its namespaces, without the Rust mark;
    // `is_enumeration` knows the attribute with its crate's path too. Catches a value renumbered
    // from 0, a namespace lost, and the mark that would make E310 refuse the type.
    let item: syn::ItemEnum = parse_quote! {
        #[derive(Clone, Copy, Debug, PartialEq, Eq)]
        pub enum Mode {
            Off = 0,
            Auto = 1,
            Manual = 5,
            Back = -1,
        }
    };
    let read = enumeration(args("name = \"Motion.MODE\""), &item).unwrap();
    assert_eq!(
        read,
        Enumeration {
            name: "Motion.MODE".into(),
            item: "Mode".into(),
            variants: vec![
                ("Off".into(), 0),
                ("Auto".into(), 1),
                ("Manual".into(), 5),
                ("Back".into(), -1),
            ],
        }
    );
    assert_eq!(
        read.declaration("rust/src/modes.rs"),
        "(* GENERATED by trust-runtime from rust/src/modes.rs - do not edit *)\n\
         NAMESPACE Motion\n\
         TYPE\n    MODE : (Off := 0, Auto := 1, Manual := 5, Back := -1);\nEND_TYPE\n\
         END_NAMESPACE\n"
    );
    assert!(read.has_variant("MANUAL") && !read.has_variant("On"));
    let marked: syn::ItemEnum = parse_quote! { #[trust_plc::trust_enum(name = "M")] pub enum M {} };
    assert!(is_enumeration(&marked.attrs[0]));
}

