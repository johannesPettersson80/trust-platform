#[test]
fn initial_values_are_literals_of_the_variables_type() {
    // Catches an initial value written as Rust writes it, which Structured Text reads otherwise or
    // not at all: a real literal has a decimal point before its exponent (IEC §6.3.2, Table 5), a
    // real given as `2` is 2.0, and a hexadecimal integer is its value (RU-26).
    let item: ItemStruct = parse_quote! {
        #[budget("1us")]
        pub struct Inits {
            #[init(true)] a: bool,
            #[init(-128)] b: i8,
            #[init(255)] c: u8,
            #[init(0x10)] d: u16,
            #[init(2)] e: f64,
            #[init(1e300)] f: f64,
            #[init(-2.5e-8)] g: f64,
            #[init(0.1)] h: f32,
            #[init(18_446_744_073_709_551_615)] i: u64,
            #[init(5u8)] j: u8,
            k: i32,
        }
    };
    let pou = function_block(args("name = \"INITS\""), &item).unwrap();
    let inits: Vec<Option<String>> = pou
        .variables
        .iter()
        .map(|variable| variable.init.as_ref().map(Value::structured_text))
        .collect();
    let expected = [
        "TRUE",
        "-128",
        "255",
        "16",
        "2.0",
        "1.0E300",
        "-2.5E-8",
        "0.1",
        "18446744073709551615",
        "5",
    ];
    let mut expected: Vec<Option<String>> =
        expected.iter().map(|text| Some((*text).into())).collect();
    expected.push(None);
    assert_eq!(inits, expected);
    // A REAL's value is the f32 its literal rounds to, not the f64.
    assert_eq!(pou.variables[7].init, Some(Value::Real(0.1_f32)));
}

#[test]
