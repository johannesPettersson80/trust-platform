//! A Rust POU is declared to Structured Text as specification 48 §6.1 gives it (RU-22 to RU-26,
//! RU-46). Every expected text is the specification's or worked out by hand from it and the
//! standard.

use proc_macro2::TokenStream;
use syn::{parse_quote, ItemFn, ItemStruct};

use crate::{
    budget, declared_kind, enumeration, function, function_block, is_budget, is_enumeration,
    is_field_attribute, is_structure, structure, DataType, Elementary, Enumeration, Kind, Pou,
    Value,
};

fn args(text: &str) -> TokenStream {
    text.parse().expect("the arguments are tokens")
}

fn refusal(result: Result<Pou, syn::Error>) -> String {
    result.expect_err("the item is refused").to_string()
}

/// The refusal of a function block with the fields `fields`.
fn fields_refusal(fields: &str) -> String {
    let item: ItemStruct = syn::parse_str(&format!(
        "#[budget(\"1us\")] pub struct Fields {{ {fields} }}"
    ))
    .expect("a struct");
    refusal(function_block(args("name = \"FIELDS\""), &item))
}

#[test]
fn a_function_blocks_declaration_is_the_specifications_text() {
    // Catches a declaration that loses a section, a type, an initial value or the mark: RU-23's text
    // for RU-22's FILTER_EMA, with the file it lies in named in the first line.
    let item: ItemStruct = parse_quote! {
        /// Exponential moving average of one input.
        #[budget("15us")]
        pub struct FilterEma {
            #[input] pub x: f64,
            #[input] #[init(0.1)] pub alpha: f64,
            #[output] pub y: f64,
            primed: bool,
        }
    };
    let pou = function_block(args("name = \"FILTER_EMA\""), &item).unwrap();
    assert_eq!(pou.kind, Kind::FunctionBlock);
    assert_eq!(pou.item, "FilterEma");
    assert_eq!(pou.budget_ns, 15_000);
    assert_eq!(
        pou.declaration("rust/src/filter.rs"),
        "(* GENERATED by trust-runtime from rust/src/filter.rs - do not edit *)\n\
         {attribute 'rust'}\n\
         FUNCTION_BLOCK FILTER_EMA\n\
         VAR_INPUT\n    EN : BOOL := TRUE;\n    x : LREAL;\n    alpha : LREAL := 0.1;\nEND_VAR\n\
         VAR_OUTPUT\n    y : LREAL;\nEND_VAR\n\
         VAR\n    primed : BOOL;\nEND_VAR\n\
         VAR_OUTPUT\n    ENO : BOOL;\nEND_VAR\n\
         END_FUNCTION_BLOCK\n"
    );
}

