//! The interfaces a Rust function block implements, `#[trust_fb(implements = "...")]`
//! (specification 48 RU-33). Every expected text is worked out by hand from RU-23, RU-30, RU-32 and
//! IEC §6.6.6.

use proc_macro2::TokenStream;
use syn::{parse_quote, ImplItemFn, ItemFn, ItemStruct};

use crate::{function, function_block, method, Pou};

fn args(text: &str) -> TokenStream {
    text.parse().expect("the arguments are tokens")
}

/// The block COUNTER with the output `count`.
fn counter() -> ItemStruct {
    parse_quote! {
        #[budget("2us")]
        pub struct Counter {
            #[output] pub count: i32,
        }
    }
}

fn refusal(result: Result<Pou, syn::Error>) -> String {
    result.expect_err("the item is refused").to_string()
}

#[test]
fn a_block_is_declared_with_the_interfaces_it_implements() {
    // RU-33, IEC §6.6.6: `FUNCTION_BLOCK COUNTER IMPLEMENTS I_COUNTER, Motion.I_RESET`, the
    // interfaces in their order with their namespaces, the spaces around each name dropped; the
    // method `count_by` after the variables, as RU-32 writes it. Catches an interface lost from
    // the declaration, which Structured Text would then refuse to assign to the interface, and one
    // written out of order or with the list's spaces.
    let mut pou = function_block(
        args("name = \"COUNTER\", implements = \" I_COUNTER ,Motion.I_RESET \""),
        &counter(),
    )
    .expect("the block is read");
    assert_eq!(pou.implements, ["I_COUNTER", "Motion.I_RESET"]);
    let count_by: ImplItemFn = parse_quote! {
        #[budget("1us")]
        pub fn count_by(&mut self, _cx: &mut Cx, amount: i32) -> Result<i32, Fault> {
            Ok(amount)
        }
    };
    pou.methods
        .push(method(TokenStream::new(), &count_by).expect("the method is read"));
    assert_eq!(
        pou.declaration("rust/src/counter.rs"),
        "(* GENERATED by trust-runtime from rust/src/counter.rs - do not edit *)\n\
         {attribute 'rust'}\n\
         FUNCTION_BLOCK COUNTER IMPLEMENTS I_COUNTER, Motion.I_RESET\n\
         VAR_INPUT\n    EN : BOOL := TRUE;\nEND_VAR\n\
         VAR_OUTPUT\n    count : DINT;\n    ENO : BOOL;\nEND_VAR\n\
         METHOD PUBLIC count_by : DINT\nVAR_INPUT\n    amount : DINT;\nEND_VAR\nEND_METHOD\n\
         END_FUNCTION_BLOCK\n"
    );
}

#[test]
fn a_block_without_implements_implements_nothing() {
    // Catches an `IMPLEMENTS` clause written without interfaces, which does not parse.
    let pou = function_block(args("name = \"COUNTER\""), &counter()).expect("the block is read");
    assert_eq!(pou.implements, Vec::<String>::new());
    assert!(pou
        .declaration("rust/src/counter.rs")
        .contains("FUNCTION_BLOCK COUNTER\n"));
}

#[test]
fn a_list_of_interfaces_structured_text_cannot_read_is_refused() {
    // IEC §6.6.6's list of interface names, each a name Structured Text can write (IEC §6.1.2,
    // §6.9) and named once, as Structured Text ignores case. Catches an empty name, a name that
    // does not parse, a reserved word and a name given twice reaching the declaration, where the
    // build would report it in the generated file instead of at the attribute.
    let cases = [
        ("\"\"", "names the interfaces the block implements"),
        ("\"I_RUN,\"", "names the interfaces the block implements"),
        (
            "\"I_RUN,,I_RESET\"",
            "names the interfaces the block implements",
        ),
        ("\"I-RUN\"", "`I-RUN` is not a Structured Text name"),
        (
            "\"Motion..I_RUN\"",
            "`Motion..I_RUN` is not a Structured Text name",
        ),
        (
            "\"INTERFACE\"",
            "`INTERFACE` is a reserved word of Structured Text",
        ),
        (
            "\"I_RUN, i_run\"",
            "`I_RUN` and `i_run` are one interface in Structured Text",
        ),
    ];
    for (list, expected) in cases {
        let message = refusal(function_block(
            args(&format!("name = \"COUNTER\", implements = {list}")),
            &counter(),
        ));
        assert!(message.contains(expected), "{list}: {message}");
    }
    let twice = refusal(function_block(
        args("name = \"COUNTER\", implements = \"I_RUN\", implements = \"I_RESET\""),
        &counter(),
    ));
    assert!(twice.contains("`implements` is given twice"), "{twice}");
    let other = refusal(function_block(
        args("name = \"COUNTER\", extends = \"BASE\""),
        &counter(),
    ));
    assert!(
        other.contains("`#[trust_fb]` takes `name = \"...\"`"),
        "{other}"
    );
}

#[test]
fn only_a_block_implements_interfaces() {
    // IEC §6.6.6: a function block or a class implements an interface, a function does not; of
    // the Rust POUs, a function block (RU-33). Catches `implements` read on a function and dropped.
    let item: ItemFn = parse_quote! {
        #[budget("1us")]
        pub fn twice(_cx: &mut Cx, a: i32) -> Result<i32, Fault> {
            Ok(a)
        }
    };
    let message = refusal(function(
        args("name = \"TWICE\", implements = \"I_RUN\""),
        &item,
    ));
    assert!(
        message.contains("`implements` belongs to `#[trust_fb]`"),
        "{message}"
    );
}
