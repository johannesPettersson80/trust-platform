//! The Structured Text declaration of a Rust POU (specification 48 RU-23).

use std::fmt::Write as _;

use crate::{Kind, Pou, Section};

/// The declaration of `pou`, after a comment that names `source`: inside a `NAMESPACE` for each
/// namespace of its name (IEC §6.9), marked `{attribute 'rust'}`, with its variables in their
/// declaration order, a new section where the section or the retention changes, and no body.
pub(crate) fn declaration(pou: &Pou, source: &str) -> String {
    let mut text = format!("(* GENERATED by trust-runtime from {source} - do not edit *)\n");
    let (namespaces, name) = match pou.name.rsplit_once('.') {
        Some((namespaces, name)) => (namespaces.split('.').collect(), name),
        None => (Vec::new(), pou.name.as_str()),
    };
    for namespace in &namespaces {
        let _ = writeln!(text, "NAMESPACE {namespace}");
    }
    text.push_str("{attribute 'rust'}\n");
    let _ = match (pou.kind, pou.result) {
        (Kind::FunctionBlock, _) => writeln!(text, "FUNCTION_BLOCK {name}"),
        (Kind::Function, Some(result)) => writeln!(text, "FUNCTION {name} : {}", result.iec()),
        (Kind::Function, None) => writeln!(text, "FUNCTION {name}"),
    };
    let mut open = None;
    for variable in &pou.variables {
        let section = (variable.section, variable.retain);
        if open != Some(section) {
            if open.is_some() {
                text.push_str("END_VAR\n");
            }
            text.push_str(match variable.section {
                Section::Input => "VAR_INPUT",
                Section::Output => "VAR_OUTPUT",
                Section::Var => "VAR",
            });
            text.push_str(if variable.retain { " RETAIN\n" } else { "\n" });
            open = Some(section);
        }
        let _ = write!(text, "    {} : {}", variable.name, variable.ty.iec());
        if let Some(init) = &variable.init {
            let _ = write!(text, " := {}", init.structured_text());
        }
        text.push_str(";\n");
    }
    if open.is_some() {
        text.push_str("END_VAR\n");
    }
    text.push_str(match pou.kind {
        Kind::FunctionBlock => "END_FUNCTION_BLOCK\n",
        Kind::Function => "END_FUNCTION\n",
    });
    for _ in &namespaces {
        text.push_str("END_NAMESPACE\n");
    }
    text
}
