//! The structures of a project's crate (specification 48 RU-25): a Rust `struct` with named `pub`
//! fields of RU-25's types, each with its initial value as a variable's, that derives `Clone` and
//! `Copy` and is marked `#[trust_struct(name = "POINT")]`. The generated declarations declare it
//! as a structure of Structured Text with its fields in their order (IEC §6.4.4.4).

use std::fmt::Write as _;

use proc_macro2::TokenStream;
use syn::spanned::Spanned;
use syn::{Attribute, Error, Fields, ItemStruct, Visibility};

use crate::literal::Value;
use crate::types::DataType;

/// A field of a structure.
#[derive(Clone, Debug, PartialEq)]
pub struct Field {
    /// Its name, the Rust field's, which Structured Text uses too.
    pub name: String,
    /// Its IEC type (RU-25).
    pub ty: DataType,
    /// Its initial value (`#[init(...)]`, RU-26); `None` starts it at its type's default.
    pub init: Option<Value>,
}

/// A structure of the crate, as `#[trust_struct]` declares it.
#[derive(Clone, Debug, PartialEq)]
pub struct Structure {
    /// Its Structured Text name, `POINT`, its namespaces before it (`Motion.POINT`, IEC §6.9).
    pub name: String,
    /// The Rust item's name, which a Rust POU's variable of it names.
    pub item: String,
    /// Its fields, in their order.
    pub fields: Vec<Field>,
}

impl Structure {
    /// The structure's generated declaration, after a comment that names `source`: inside a
    /// `NAMESPACE` for each namespace of its name, its fields in their order with their initial
    /// values, without `{attribute 'rust'}` since it has no body (RU-25).
    #[must_use]
    pub fn declaration(&self, source: &str) -> String {
        let mut text = format!("(* GENERATED by trust-runtime from {source} - do not edit *)\n");
        let (namespaces, name) = crate::render::split_name(&self.name);
        for namespace in &namespaces {
            let _ = writeln!(text, "NAMESPACE {namespace}");
        }
        let _ = write!(text, "TYPE\n    {name} :\n    STRUCT\n");
        for field in &self.fields {
            let _ = write!(text, "        {} : {}", field.name, field.ty.iec());
            if let Some(init) = &field.init {
                let _ = write!(text, " := {}", init.structured_text());
            }
            text.push_str(";\n");
        }
        text.push_str("    END_STRUCT;\nEND_TYPE\n");
        for _ in &namespaces {
            text.push_str("END_NAMESPACE\n");
        }
        text
    }
}

/// Whether `attribute` is `#[trust_struct]`, also written with its crate's path.
#[must_use]
pub fn is_structure(attribute: &Attribute) -> bool {
    crate::last_segment_is(attribute, "trust_struct")
}

/// Reads the structure `item`, whose `#[trust_struct]` has the arguments `args`.
///
/// # Errors
///
/// An error at the part of the item that breaks a rule of specification 48 RU-25, naming the rule.
pub fn structure(args: TokenStream, item: &ItemStruct) -> Result<Structure, Error> {
    let name = crate::declared_name(
        args,
        item.ident.span(),
        "a Rust structure names itself for Structured Text: `#[trust_struct(name = \"POINT\")]` \
         (specification 48 RU-25)",
    )?;
    if !matches!(item.vis, Visibility::Public(_)) {
        return Err(Error::new(
            item.ident.span(),
            "a Rust structure is `pub`, as the variables of the Rust POUs that hold it are \
             (specification 48 RU-25)",
        ));
    }
    if !item.generics.params.is_empty() || item.generics.where_clause.is_some() {
        return Err(Error::new(
            item.generics.span(),
            "a Rust structure has no generic parameters: it lies in the program's areas with one \
             layout (specification 48 RU-25)",
        ));
    }
    let derived = crate::enumeration::derived(&item.attrs)?;
    if !["Clone", "Copy"]
        .iter()
        .all(|wanted| derived.iter().any(|name| name == wanted))
    {
        return Err(Error::new(
            item.ident.span(),
            "a Rust structure derives `Clone` and `Copy`, as every type of a Rust POU's variables \
             is copied: `#[derive(Clone, Copy)]` (specification 48 RU-25)",
        ));
    }
    let Fields::Named(named) = &item.fields else {
        return Err(Error::new(
            item.fields.span(),
            "a Rust structure's fields are named: `pub struct Point { pub x: f64 }` (specification \
             48 RU-25)",
        ));
    };
    if named.named.is_empty() {
        return Err(Error::new(
            item.ident.span(),
            "a structure has one field at least (IEC §6.4.4.4)",
        ));
    }
    let mut fields: Vec<Field> = Vec::with_capacity(named.named.len());
    for field in &named.named {
        let Some(ident) = &field.ident else { continue };
        if !matches!(field.vis, Visibility::Public(_)) {
            return Err(Error::new(
                ident.span(),
                "a field of a Rust structure is `pub`: the program's generated code builds the \
                 structure from Structured Text's (specification 48 RU-25)",
            ));
        }
        let mut init = None;
        for attribute in &field.attrs {
            if attribute.path().is_ident("init") {
                if init.is_some() {
                    return Err(Error::new(attribute.span(), "`#[init]` is given twice"));
                }
                init = Some(attribute.parse_args::<syn::Expr>()?);
            } else if crate::is_field_attribute(attribute) {
                return Err(Error::new(
                    attribute.span(),
                    "a structure's field takes `#[init]` only: it is no POU's variable, which \
                     `#[input]`, `#[output]` and `#[retain]` place (specification 48 RU-25)",
                ));
            }
        }
        let name = crate::variable_name(ident)?;
        if let Some(other) = fields
            .iter()
            .find(|other| other.name.eq_ignore_ascii_case(&name))
        {
            return Err(Error::new(
                ident.span(),
                format!(
                    "`{}` and `{name}` are one name in Structured Text, which ignores case (IEC \
                     §6.1.2)",
                    other.name
                ),
            ));
        }
        let ty = DataType::of(&field.ty)?;
        let init = init
            .map(|value| crate::literal::initial_of(&value, &ty))
            .transpose()?;
        fields.push(Field { name, ty, init });
    }
    Ok(Structure {
        name,
        item: item.ident.to_string(),
        fields,
    })
}
