//! The enumerations of a project's crate (specification 48 RU-25): a Rust `enum` whose variants hold
//! no data, each with an explicit value within `INT`, that derives `Clone` and `Copy` and is marked
//! `#[trust_enum(name = "MODE")]`. The generated declarations declare it as a closed enumeration of
//! Structured Text (specification 02 §3.1) with the variants' names and values.

use std::fmt::Write as _;

use proc_macro2::TokenStream;
use syn::punctuated::Punctuated;
use syn::spanned::Spanned;
use syn::{Attribute, Error, Expr, ExprLit, ExprUnary, Fields, ItemEnum, Lit, Path, Token, UnOp};

/// An enumeration of the crate, as `#[trust_enum]` declares it.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Enumeration {
    /// Its Structured Text name, `MODE`, its namespaces before it (`Motion.MODE`, IEC §6.9).
    pub name: String,
    /// The Rust item's name, which a Rust POU's variable of it names.
    pub item: String,
    /// Its variants' names and values, in their order; the first is the type's default.
    pub variants: Vec<(String, i64)>,
}

impl Enumeration {
    /// The enumeration's generated declaration, after a comment that names `source`: inside a
    /// `NAMESPACE` for each namespace of its name, a closed enumeration with its variants' names
    /// and values, without `{attribute 'rust'}` since it has no body (RU-25).
    #[must_use]
    pub fn declaration(&self, source: &str) -> String {
        let mut text = format!("(* GENERATED by trust-runtime from {source} - do not edit *)\n");
        let (namespaces, name) = crate::render::split_name(&self.name);
        for namespace in &namespaces {
            let _ = writeln!(text, "NAMESPACE {namespace}");
        }
        let values: Vec<String> = self
            .variants
            .iter()
            .map(|(variant, value)| format!("{variant} := {value}"))
            .collect();
        let _ = write!(
            text,
            "TYPE\n    {name} : ({});\nEND_TYPE\n",
            values.join(", ")
        );
        for _ in &namespaces {
            text.push_str("END_NAMESPACE\n");
        }
        text
    }

    /// Whether `name` is one of its variants, compared as Structured Text compares names.
    #[must_use]
    pub fn has_variant(&self, name: &str) -> bool {
        self.variants
            .iter()
            .any(|(variant, _)| variant.eq_ignore_ascii_case(name))
    }
}

/// Whether `attribute` is `#[trust_enum]`, also written with its crate's path.
#[must_use]
pub fn is_enumeration(attribute: &Attribute) -> bool {
    crate::last_segment_is(attribute, "trust_enum")
}

/// Reads the enumeration `item`, whose `#[trust_enum]` has the arguments `args`.
///
/// # Errors
///
/// An error at the part of the item that breaks a rule of specification 48 RU-25, naming the rule.
pub fn enumeration(args: TokenStream, item: &ItemEnum) -> Result<Enumeration, Error> {
    let name = crate::declared_name(
        args,
        item.ident.span(),
        "a Rust enumeration names itself for Structured Text: `#[trust_enum(name = \"MODE\")]` \
         (specification 48 RU-25)",
    )?;
    if !matches!(item.vis, syn::Visibility::Public(_)) {
        return Err(Error::new(
            item.ident.span(),
            "a Rust enumeration is `pub`, as the variables of the Rust POUs that hold it are \
             (specification 48 RU-25)",
        ));
    }
    if !item.generics.params.is_empty() || item.generics.where_clause.is_some() {
        return Err(Error::new(
            item.generics.span(),
            "a Rust enumeration has no generic parameters (specification 48 RU-25)",
        ));
    }
    let derived = derived(&item.attrs)?;
    if !["Clone", "Copy"]
        .iter()
        .all(|wanted| derived.iter().any(|name| name == wanted))
    {
        return Err(Error::new(
            item.ident.span(),
            "a Rust enumeration derives `Clone` and `Copy`, as every type of a Rust POU's \
             variables is copied: `#[derive(Clone, Copy)]` (specification 48 RU-25)",
        ));
    }
    if item.variants.is_empty() {
        return Err(Error::new(
            item.ident.span(),
            "an enumeration has one value at least (IEC §6.4.4.2)",
        ));
    }
    let mut variants: Vec<(String, i64)> = Vec::with_capacity(item.variants.len());
    for variant in &item.variants {
        if !matches!(variant.fields, Fields::Unit) {
            return Err(Error::new(
                variant.fields.span(),
                "a variant of a Rust enumeration holds no data: it is one of Structured Text's \
                 enumerated values (specification 48 RU-25)",
            ));
        }
        let Some((_, value)) = &variant.discriminant else {
            return Err(Error::new(
                variant.ident.span(),
                "each variant of a Rust enumeration has its value, which Structured Text holds: \
                 `Off = 0` (specification 48 RU-25)",
            ));
        };
        let value = integer(value)
            .and_then(|value| i16::try_from(value).ok())
            .map(i64::from)
            .ok_or_else(|| {
                Error::new(
                    value.span(),
                    "a variant's value is an integer literal within INT, -32768 to 32767, the \
                     base of Structured Text's enumerations (specification 02 §3.1)",
                )
            })?;
        let variant_name = variant.ident.to_string();
        if !crate::is_identifier(&variant_name) {
            return Err(Error::new(
                variant.ident.span(),
                format!(
                    "`{variant_name}` is not an IEC identifier (IEC §6.1.2), which Structured \
                     Text names the value by"
                ),
            ));
        }
        if crate::names::is_reserved(&variant_name) {
            return Err(Error::new(
                variant.ident.span(),
                format!(
                    "{}: rename the value",
                    crate::names::reserved_reason(&variant_name)
                ),
            ));
        }
        if let Some((other, _)) = variants
            .iter()
            .find(|(other, _)| other.eq_ignore_ascii_case(&variant_name))
        {
            return Err(Error::new(
                variant.ident.span(),
                format!(
                    "`{other}` and `{variant_name}` are one name in Structured Text, which ignores \
                     case (IEC §6.1.2)"
                ),
            ));
        }
        variants.push((variant_name, value));
    }
    Ok(Enumeration {
        name,
        item: item.ident.to_string(),
        variants,
    })
}

/// The names of the traits `attributes` derive.
pub(crate) fn derived(attributes: &[Attribute]) -> Result<Vec<String>, Error> {
    let mut names = Vec::new();
    for attribute in attributes {
        if attribute.path().is_ident("derive") {
            let paths =
                attribute.parse_args_with(Punctuated::<Path, Token![,]>::parse_terminated)?;
            names.extend(
                paths
                    .iter()
                    .filter_map(|path| path.segments.last())
                    .map(|segment| segment.ident.to_string()),
            );
        }
    }
    Ok(names)
}

/// The value of an integer literal, `-` before one allowed.
fn integer(expression: &Expr) -> Option<i128> {
    match expression {
        Expr::Lit(ExprLit {
            lit: Lit::Int(literal),
            ..
        }) => literal.base10_parse().ok(),
        Expr::Unary(ExprUnary {
            op: UnOp::Neg(_),
            expr,
            ..
        }) => integer(expr).map(|value| -value),
        _ => None,
    }
}
