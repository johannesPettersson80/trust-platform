fn quality_name(point_name: &str) -> String {
    format!("{point_name}_quality")
}

fn address_comment(address: &AdsPointAddress) -> String {
    match address {
        AdsPointAddress::Symbol(name) => format!("symbol {name}"),
        AdsPointAddress::Index {
            index_group,
            index_offset,
            size,
        } => format!("index group=0x{index_group:08X} offset=0x{index_offset:08X} size={size}"),
    }
}

fn sanitize_st_comment(text: &str) -> String {
    text.replace("*)", "* )")
}
