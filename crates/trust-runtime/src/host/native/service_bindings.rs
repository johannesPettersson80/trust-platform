//! A service's bindings (specification 48 RU-62): the Rust module that `trust-dev service bindings`
//! writes from the symbol table of the project's image. It names each variable of the program that
//! holds one elementary value, with its Rust type, so that the compiler checks a service's paths and
//! types against the program; a variable the service's `writes` names is a `Writable` handle, which
//! alone `Service::set` takes.

use std::fmt::Write as _;

use trust_runtime_core::native::image::{type_kind as kind, Image};
use trust_runtime_core::native::memory::{type_shape, TypeShape};
use trust_runtime_core::native::reflect::{resolve_writable, walk_variables, Located};

/// The names Rust reserves, which a binding writes as a raw identifier (`r#match`).
const KEYWORDS: [&str; 46] = [
    "abstract", "as", "async", "await", "become", "box", "break", "const", "continue", "do", "dyn",
    "else", "enum", "extern", "false", "final", "fn", "for", "gen", "if", "impl", "in", "let",
    "loop", "macro", "match", "mod", "move", "mut", "override", "priv", "pub", "ref", "return",
    "static", "struct", "trait", "true", "try", "type", "typeof", "unsafe", "unsized", "use",
    "virtual", "where",
];

/// One module of the bindings: its constants, then its modules, each in declaration order.
#[derive(Default)]
struct Module {
    constants: Vec<String>,
    modules: Vec<(String, Module)>,
}

impl Module {
    /// The module at `names` below this one, made when it is missing.
    fn at(&mut self, names: &[&str]) -> &mut Self {
        let Some((first, rest)) = names.split_first() else {
            return self;
        };
        let index = match self.modules.iter().position(|(name, _)| name == first) {
            Some(index) => index,
            None => {
                self.modules.push(((*first).to_string(), Self::default()));
                self.modules.len() - 1
            }
        };
        self.modules[index].1.at(rest)
    }

    fn write(&self, out: &mut String, depth: usize) {
        let indent = "    ".repeat(depth);
        for constant in &self.constants {
            let _ = writeln!(out, "{indent}{constant}");
        }
        for (name, module) in &self.modules {
            let _ = writeln!(out, "{indent}pub mod {} {{", rust_name(name));
            module.write(out, depth + 1);
            let _ = writeln!(out, "{indent}}}");
        }
    }
}

/// The bindings of the service `service` whose `writes` are `writes`, from `image`.
///
/// # Errors
///
/// A path of `writes` that the image holds no writable elementary variable at, naming it, and an
/// image whose tables do not read.
pub fn service_bindings(
    image: &Image<'_>,
    service: &str,
    writes: &[String],
) -> Result<String, String> {
    let writable: Vec<Located> = writes
        .iter()
        .map(|path| {
            resolve_writable(image, path)
                .map_err(|error| format!("[services.{service}] writes \"{path}\": {error}"))
        })
        .collect::<Result<_, _>>()?;
    let mut root = Module::default();
    let mut failure = None;
    walk_variables(image, &mut |path, located| {
        let ty = match type_shape(image, located.type_index) {
            Ok(shape) => rust_type(&shape),
            Err(error) => {
                failure.get_or_insert_with(|| error.to_string());
                None
            }
        };
        let Some(ty) = ty else { return };
        let names: Vec<&str> = path.split('.').collect();
        let Some((leaf, modules)) = names.split_last() else {
            return;
        };
        let handle = if writable.contains(&located) {
            "Writable"
        } else {
            "Variable"
        };
        root.at(modules).constants.push(format!(
            "pub const {}: trust_service::{handle}<{ty}> = trust_service::{handle}::new({path:?});",
            rust_name(leaf)
        ));
    })
    .map_err(|error| error.to_string())?;
    if let Some(error) = failure {
        return Err(error);
    }
    let hash: String = image
        .header()
        .source_hash
        .iter()
        .map(|byte| format!("{byte:02x}"))
        .collect();
    let mut out = format!(
        "// GENERATED by `trust-dev service bindings {service}` from the image of the sources with\n\
         // SHA-256 {hash}: do not edit, run the command again when the program changes\n\
         // (specification 48 RU-62).\n\
         #![allow(non_snake_case, non_upper_case_globals, dead_code)]\n\n"
    );
    root.write(&mut out, 0);
    Ok(out)
}

/// The Rust type a variable of `shape` reads as, `None` for one the bindings leave out: an array
/// and the types without a single value, which the walk does not visit.
fn rust_type(shape: &TypeShape) -> Option<&'static str> {
    let kind = match shape {
        TypeShape::Elementary(kind) | TypeShape::Subrange(kind) => *kind,
        TypeShape::Text { .. } | TypeShape::Enumeration { .. } => return Some("String"),
        TypeShape::Array { .. } | TypeShape::Other => return None,
    };
    Some(match kind {
        kind::BOOL => "bool",
        kind::SINT => "i8",
        kind::INT => "i16",
        kind::DINT => "i32",
        kind::LINT => "i64",
        kind::USINT | kind::BYTE => "u8",
        kind::UINT | kind::WORD => "u16",
        kind::UDINT | kind::DWORD => "u32",
        kind::ULINT | kind::LWORD => "u64",
        kind::REAL => "f32",
        kind::LREAL => "f64",
        kind::TIME | kind::LTIME => "std::time::Duration",
        // A date or a time of day is its count of milliseconds or nanoseconds, as variables.read
        // gives it.
        kind::DATE | kind::LDATE | kind::TOD | kind::LTOD | kind::DT | kind::LDT => "i64",
        kind::CHAR | kind::WCHAR => "String",
        _ => return None,
    })
}

/// `name` as a Rust identifier: a keyword as a raw identifier, and `self`, `Self`, `super`,
/// `crate` and `_`, which no raw identifier spells, with a trailing underscore.
fn rust_name(name: &str) -> String {
    if matches!(name, "self" | "Self" | "super" | "crate" | "_") {
        format!("{name}_")
    } else if KEYWORDS.contains(&name) {
        format!("r#{name}")
    } else {
        name.to_string()
    }
}

