//! The build of a program whose project has a Rust crate (specification 48 §9.3): the generated
//! crate becomes a cargo package that depends on the project's crate, the SDK's crates are taken
//! from the toolchain's sources, and the toolchain's cargo and compiler build the whole crate graph
//! into one module with the flags of specification 44 §4.5, which the build without a crate passes
//! to the compiler itself (`Toolchain::compile`).
//!
//! Every crate of the graph is compiled from source with the module's code generation flags, so
//! the project's crate and the generated code share one interface crate, and one link with
//! link-time optimization makes the module. The build runs offline, its cargo in the toolchain's
//! own home (RU-75): the SDK and the crates.io crates it is built from come from the toolchain's
//! copies, the project's other dependencies from the project's vendored sources (RU-10, RU-12).

use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::Command;

use super::rust_messages::{self, RustDiagnostic, RustSeverity, REMAPPED_CRATE};
use super::toolchain::{cpu, triple, LINKER_SCRIPT};
use super::{NativeError, RustFailure, Toolchain};
use trust_runtime_core::deployment::RustCrate;
use trust_runtime_core::native::image::Target;

/// The name the generated code gives the project's crate.
pub(super) const PROJECT_CRATE: &str = "trust_project";

/// The colour the build asks of its cargo, whose report is text that the build filters and passes
/// on, never a terminal's: cargo writes it without colour whatever the user's environment asks of
/// cargo (`CARGO_TERM_COLOR`), so that the report names the project's diagnostics in plain text
/// (RU-44) and the user's settings play no part (RU-75).
const NO_COLOUR: &str = "never";

/// The variables of the user's environment, besides `CARGO` and cargo's `CARGO_` configuration,
/// that give cargo's compiler flags, wrap the compiler or unlock its unstable features, which the
/// build's cargo runs without (RU-75).
const USER_COMPILER_SETTINGS: [&str; 5] = [
    "RUSTFLAGS",
    "RUSTDOCFLAGS",
    "RUSTC_WRAPPER",
    "RUSTC_WORKSPACE_WRAPPER",
    "RUSTC_BOOTSTRAP",
];

/// The SDK's crates, which the build takes from the toolchain's sources whatever version a
/// manifest names (RU-12); of them, a crate outside the SDK may name only those RU-12 publishes for
/// projects (RU-20, `crate_graph`).
const SDK_CRATES: [&str; 5] = [
    "trust-plc",
    "trust-plc-macros",
    "trust-plc-decl",
    "trust-plc-abi",
    "trust-plc-lib",
];

/// The project's crate a build links.
#[derive(Debug, Clone)]
pub(super) struct ProjectCrate {
    /// Its folder, `rust/` of the project.
    pub(super) folder: PathBuf,
    /// Its folder as the project names it, with `/` (`rust`): the compiler's diagnostics name the
    /// crate's files below it (specification 48 RU-44).
    pub(super) label: String,
    /// Its package's name.
    pub(super) package: String,
    /// The folder of layer 1, the bindings' crate `trust_st`, when the crate calls Structured
    /// Text (specification 48 RU-39).
    pub(super) bindings: Option<PathBuf>,
    /// Whether the image is a debug image, whose layer 1 holds the debugger's statement hooks, its
    /// cargo feature `hooks` (specification 44 §13).
    pub(super) debug: bool,
}

/// The manifest of layer 1, the crate `trust_st` whose library `st` holds the Structured Text that
/// the project's crate calls (specification 48 RU-39), on the SDK of this toolchain's version.
fn layer_one_manifest() -> String {
    let version = env!("CARGO_PKG_VERSION");
    format!(
        "# Generated by truST from the project's Structured Text (specification 48 RU-39); do not \
         edit.\n[package]\nname = \"trust_st\"\nversion = \"0.0.0\"\nedition = \"2024\"\n\
         publish = false\n\n[lib]\nname = \"st\"\npath = \"src/lib.rs\"\n\n[features]\nhooks = []\n\n\
         [dependencies]\n\
         trust-plc = \"={version}\"\ntrust-plc-abi = \"={version}\"\ntrust-plc-lib = \"={version}\"\n"
    )
}

/// Writes layer 1 with the library `library` into `folder`, the project's `build/trust_st`
/// (specification 48 RU-39), with the `.gitignore` that keeps the folder out of version control:
/// only the files whose text changed, so that cargo compiles it again only when the Structured
/// Text it holds changed.
///
/// # Errors
///
/// [`NativeError::Toolchain`] when a file cannot be written.
pub(super) fn write_layer_one(folder: &Path, library: &str) -> Result<(), NativeError> {
    for (file, text) in [
        (folder.join(".gitignore"), "*\n".to_string()),
        (folder.join("Cargo.toml"), layer_one_manifest()),
        (folder.join("src").join("lib.rs"), library.to_string()),
    ] {
        if std::fs::read_to_string(&file).is_ok_and(|old| old == text) {
            continue;
        }
        let failed =
            |error: std::io::Error| NativeError::Toolchain(format!("{}: {error}", file.display()));
        if let Some(parent) = file.parent() {
            std::fs::create_dir_all(parent).map_err(failed)?;
        }
        std::fs::write(&file, text).map_err(failed)?;
    }
    Ok(())
}

/// The crates of the toolchain's folder `vendor`, the copies of the crates.io crates the SDK is
/// built from, by name and folder, in the order of their names (specification 48 RU-74).
///
/// # Errors
///
/// [`NativeError::Toolchain`] when the folder cannot be read.
fn vendored_crates(vendor: &Path) -> Result<Vec<(String, PathBuf)>, NativeError> {
    let failed =
        |error: std::io::Error| NativeError::Toolchain(format!("{}: {error}", vendor.display()));
    let mut crates = Vec::new();
    for entry in std::fs::read_dir(vendor).map_err(failed)? {
        let folder = entry.map_err(failed)?.path();
        if let Some(name) = folder.file_name().and_then(|name| name.to_str())
            && folder.join("Cargo.toml").is_file()
        {
            crates.push((name.to_string(), folder.clone()));
        }
    }
    crates.sort();
    Ok(crates)
}

/// `path` as cargo reads a path in a manifest: with `/` between its parts, and without the verbatim
/// prefix that a canonical path carries on Windows (`\\?\D:\…`, `\\?\UNC\server\…`), which cargo
/// refuses as an "invalid path url". trust-sim opens a machine test's project at its canonical
/// folder, so the build of a project with Rust POUs meets such a path there (specification 48
/// RU-58).
fn cargo_path(path: &Path) -> String {
    let text = path.display().to_string();
    let plain = match text.strip_prefix(r"\\?\") {
        Some(rest) => rest
            .strip_prefix(r"UNC\")
            .map_or_else(|| rest.to_owned(), |unc| format!(r"\\{unc}")),
        None => text.clone(),
    };
    plain.replace('\\', "/")
}

/// The manifest of the generated crate's package in `work`, for `target`, depending on `project`
/// and on the SDK's crates in `sdk`, with the crates of `vendored` (`vendored_crates`) in place of
/// crates.io's.
fn manifest(
    target: Target,
    sdk: &Path,
    vendored: &[(String, PathBuf)],
    project: &ProjectCrate,
) -> String {
    let path = |crate_name: &str| cargo_path(&sdk.join(crate_name));
    let mut text = String::from(
        "[package]\nname = \"trust_module\"\nversion = \"0.0.0\"\nedition = \"2024\"\npublish = false\n\n\
         [[bin]]\nname = \"trust_module\"\npath = \"module.rs\"\ntest = false\nbench = false\n\n\
         [dependencies]\n",
    );
    // The SDK too: the generated code reads a Rust POU's variables through its types (RU-25).
    for crate_name in ["trust-plc-abi", "trust-plc-lib", "trust-plc"] {
        let _ = writeln!(text, "{crate_name} = {{ path = \"{}\" }}", path(crate_name));
    }
    // A computer's module takes the memory functions from trust-plc-mem; a chip's target builtins
    // have them (specification 44 §4.5).
    if target.is_computer() {
        let _ = writeln!(
            text,
            "trust-plc-mem = {{ path = \"{}\" }}",
            path("trust-plc-mem")
        );
    }
    let _ = writeln!(
        text,
        "{PROJECT_CRATE} = {{ path = \"{}\", package = \"{}\" }}",
        cargo_path(&project.folder),
        project.package
    );
    // Layer 1, whose types and functions the generated code takes (specification 48 §9.2).
    if let Some(bindings) = &project.bindings {
        let features = if project.debug {
            ", features = [\"hooks\"]"
        } else {
            ""
        };
        let _ = writeln!(
            text,
            "trust_st = {{ path = \"{}\"{features} }}",
            cargo_path(bindings)
        );
    }
    text.push_str("\n[patch.crates-io]\n");
    for crate_name in SDK_CRATES {
        let _ = writeln!(text, "{crate_name} = {{ path = \"{}\" }}", path(crate_name));
    }
    // The crates.io crates the SDK is built from come from the toolchain's copies, so its cargo
    // needs no registry (RU-75); the build gives cargo their build scripts' output (RU-74).
    for (crate_name, folder) in vendored {
        let _ = writeln!(
            text,
            "{crate_name} = {{ path = \"{}\" }}",
            cargo_path(folder)
        );
    }
    // The module's code generation of specification 44 §4.5: one unit, link-time optimization,
    // abort on panic, integer overflow without checks.
    text.push_str(
        "\n[profile.release]\nopt-level = 2\ncodegen-units = 1\nlto = \"fat\"\npanic = \"abort\"\n\
         overflow-checks = false\ndebug = 0\n\n[workspace]\n",
    );
    text
}

/// The build's package that [`write_package`] wrote, with every path absolute.
struct Package {
    cargo: PathBuf,
    sdk: PathBuf,
    work: PathBuf,
    project: ProjectCrate,
}

/// Writes the build's package into `work`: the generated crate `source` as `module.rs`, the
/// linker script, the manifest for `target` (`manifest`) and the project's `Cargo.lock`, whose
/// versions the build keeps (RU-10).
///
/// # Errors
///
/// [`NativeError::Toolchain`] when the toolchain has no cargo and SDK sources, or a file cannot be
/// written.
fn write_package(
    toolchain: &Toolchain,
    source: &str,
    target: Target,
    work: &Path,
    project: &ProjectCrate,
) -> Result<Package, NativeError> {
    let (Some(cargo), Some(sdk)) = (&toolchain.cargo, &toolchain.sdk) else {
        return Err(NativeError::Toolchain(
            "this toolchain has no cargo and SDK sources, which build a project with Rust POUs \
             (specification 48 §9.3): build its folder again with \
             scripts/native/build_toolchain_libraries.sh"
                .into(),
        ));
    };
    // Cargo runs in the build's folder, so every path it is given is absolute: a project named
    // `.` would otherwise be looked for below that folder.
    let absolute = |path: &Path| {
        std::path::absolute(path)
            .map_err(|error| NativeError::Toolchain(format!("{}: {error}", path.display())))
    };
    let work = absolute(work)?;
    let project = ProjectCrate {
        folder: absolute(&project.folder)?,
        label: project.label.clone(),
        package: project.package.clone(),
        bindings: project.bindings.as_deref().map(absolute).transpose()?,
        debug: project.debug,
    };
    let failed =
        |error: std::io::Error| NativeError::Toolchain(format!("{}: {error}", work.display()));
    std::fs::create_dir_all(&work).map_err(failed)?;
    let vendored = match &toolchain.vendor {
        Some(vendor) => vendored_crates(vendor)?,
        None => Vec::new(),
    };
    std::fs::write(work.join("module.rs"), source)
        .and_then(|()| std::fs::write(work.join("module.x"), LINKER_SCRIPT))
        .and_then(|()| {
            std::fs::write(
                work.join("Cargo.toml"),
                manifest(target, sdk, &vendored, &project),
            )
        })
        .map_err(failed)?;
    // The versions the project's lock pins are kept: the build starts from it (RU-10).
    let lock = project.folder.join("Cargo.lock");
    if lock.is_file() {
        std::fs::copy(&lock, work.join("Cargo.lock")).map_err(failed)?;
    }
    Ok(Package {
        cargo: cargo.clone(),
        sdk: sdk.clone(),
        work,
        project,
    })
}

/// What [`compile`] gives.
pub(super) struct Compiled {
    /// The linked module, an ELF file, as [`Toolchain::compile`] gives it for a project without a
    /// crate.
    pub(super) elf: Vec<u8>,
    /// The compiler's report of each function's stack frame.
    pub(super) remarks: String,
    /// The warnings of the project's crate (specification 48 RU-44).
    pub(super) warnings: Vec<RustDiagnostic>,
    /// The crates of the scan crate graph that the image lists (specification 44 §5.12).
    pub(super) crates: Vec<RustCrate>,
}

/// Compiles the crate `source` for `target` in folder `work` with the project's crate `project`.
///
/// # Errors
///
/// [`NativeError::Rust`] when the project's crate does not compile, with the compiler's report and
/// the crate's diagnostics, and [`NativeError::Toolchain`] when the toolchain has no cargo or SDK
/// sources or the build fails otherwise, with cargo's and the compiler's report.
pub(super) fn compile(
    toolchain: &Toolchain,
    source: &str,
    target: Target,
    entries: &[String],
    work: &Path,
    project: &ProjectCrate,
) -> Result<Compiled, NativeError> {
    let Package {
        cargo,
        sdk,
        work,
        project,
    } = write_package(toolchain, source, target, work, project)?;
    let (cargo, sdk, work, project) = (&cargo, &sdk, &work, &project);
    let script = work.join("module.x");
    let flags = rust_flags(toolchain, target, work, sdk, project);
    let crates = check_graph(cargo, toolchain, sdk, target, work, project)?;
    let mut command = cargo_command(cargo, toolchain, work);
    command
        .args(["rustc", "--offline", "--release", "--bin", "trust_module"])
        // The compiler's diagnostics as JSON messages, each with its place (RU-44).
        .args(["--message-format", "json"])
        .args(["--target", triple(target)]);
    // The output of the vendored crates' build scripts, which cargo takes instead of compiling and
    // running the scripts (RU-74).
    if let Some(overrides) = toolchain
        .vendor
        .as_ref()
        .map(|vendor| vendor.join("build-scripts.toml"))
        .filter(|overrides| overrides.is_file())
    {
        command.arg("--config").arg(overrides);
    }
    command
        .arg("--")
        .args(["--cfg", "trust_module", "-C", "remark=prolog-epilog"])
        .arg("-C")
        .arg(format!("linker={}", toolchain.linker.display()))
        .args(["-C", "linker-flavor=ld.lld"])
        .arg("-C")
        .arg(format!("link-arg=-T{}", script.display()))
        .args(["-C", "link-arg=--pie", "-C", "link-arg=--no-dynamic-linker"])
        .args(["-C", "link-arg=-nostdlib", "-C", "link-arg=--emit-relocs"]);
    for entry in entries {
        command
            .arg("-C")
            .arg(format!("link-arg=--undefined={entry}"));
    }
    command.env("CARGO_ENCODED_RUSTFLAGS", flags.join("\u{1f}"));
    let result = command
        .output()
        .map_err(|error| NativeError::Toolchain(format!("{}: {error}", cargo.display())))?;
    let messages = rust_messages::read(&result.stdout, &project.label);
    if !result.status.success() {
        return Err(failure(messages, &result.stderr));
    }
    let output = work
        .join("target")
        .join(triple(target))
        .join("release")
        .join("trust_module");
    let module = std::fs::read(&output)
        .map_err(|error| NativeError::Toolchain(format!("{}: {error}", output.display())))?;
    Ok(Compiled {
        elf: module,
        remarks: messages.text,
        warnings: messages.diagnostics,
        crates,
    })
}

/// The flags of every crate of the graph, which [`compile`] and [`check`] give cargo alike:
/// position-independent code without RELRO, the module's CPU, the build's folders kept out of the
/// module, so that the same project builds the same bytes wherever it lies (specification 44
/// NX-07), and the SDK's prebuilt macros.
fn rust_flags(
    toolchain: &Toolchain,
    target: Target,
    work: &Path,
    sdk: &Path,
    project: &ProjectCrate,
) -> Vec<String> {
    let (cpu, features) = cpu(target);
    // The flags of every crate of the graph: position-independent code without RELRO, the module's
    // CPU, and the build's folders kept out of the module, so that the same project builds the same
    // bytes wherever it lies (specification 44 NX-07).
    let mut flags = vec![
        "-C".to_string(),
        "relocation-model=pic".into(),
        "-C".into(),
        "relro-level=off".into(),
        "-C".into(),
        format!("target-cpu={cpu}"),
        "-C".into(),
        format!("target-feature={features}"),
        format!("--remap-path-prefix={}=.", work.display()),
        format!(
            "--remap-path-prefix={}={REMAPPED_CRATE}",
            project.folder.display()
        ),
        format!("--remap-path-prefix={}=sdk", sdk.display()),
    ];
    flags.push(format!(
        "--remap-path-prefix={}=registry",
        toolchain.cargo_home.join("registry").display()
    ));
    if let Some(vendor) = &toolchain.vendor {
        flags.push(format!("--remap-path-prefix={}=vendor", vendor.display()));
    }
    // The SDK's macros from the toolchain's prebuilt library: `trust-plc` then has no dependency on
    // them, so no procedural macro is compiled for the computer (specification 48 RU-74, RU-09).
    // The library's folder is a dependency path too: a crate that uses `trust-plc` finds the macros
    // as its dependency there, which `--extern` names only for the crates that use them directly.
    if let Some(macros) = &toolchain.macros {
        flags.extend([
            "--cfg".to_string(),
            "trust_prebuilt_macros".into(),
            "--extern".into(),
            format!("trust_plc_macros={}", macros.display()),
        ]);
        if let Some(folder) = macros.parent() {
            flags.extend(["-L".to_string(), format!("dependency={}", folder.display())]);
        }
    }
    flags
}

/// The error of a cargo run that failed with the compiler's `messages` and cargo's own `stderr`:
/// the crate's when its errors explain it, the toolchain's otherwise, such as a link that fails.
/// The report holds the compiler's messages, then cargo's own lines, the stack remarks left out.
fn failure(messages: rust_messages::Messages, stderr: &[u8]) -> NativeError {
    let cargo_says = String::from_utf8_lossy(stderr);
    let report: String = messages
        .text
        .lines()
        .chain(cargo_says.lines())
        .filter(|line| !line.starts_with("note: <unknown file>:0:0 prolog-epilog"))
        .collect::<Vec<_>>()
        .join("\n");
    let crate_errors = messages
        .diagnostics
        .iter()
        .any(|diagnostic| diagnostic.severity == RustSeverity::Error);
    if !crate_errors {
        return NativeError::Toolchain(report);
    }
    NativeError::Rust(RustFailure {
        report,
        diagnostics: messages.diagnostics,
    })
}

/// Checks the crate `source` for `target` in folder `work` with the project's crate `project` as
/// [`compile`] builds them, without code or a link: the toolchain's `cargo check`, offline, on the
/// same package with the same flags, after the same checks of the scan crate graph (specification
/// 11 §6.8.1c). Cargo keeps what it checked in `work`, beside what a build compiled.
///
/// # Errors
///
/// As [`compile`]: [`NativeError::Rust`] when the project's crate does not compile, with its
/// diagnostics, and [`NativeError::Toolchain`] otherwise.
pub(super) fn check(
    toolchain: &Toolchain,
    source: &str,
    target: Target,
    work: &Path,
    project: &ProjectCrate,
) -> Result<Vec<RustDiagnostic>, NativeError> {
    let Package {
        cargo,
        sdk,
        work,
        project,
    } = write_package(toolchain, source, target, work, project)?;
    let (cargo, sdk, work, project) = (&cargo, &sdk, &work, &project);
    let flags = rust_flags(toolchain, target, work, sdk, project);
    check_graph(cargo, toolchain, sdk, target, work, project)?;
    let mut command = cargo_command(cargo, toolchain, work);
    command
        .args(["check", "--offline", "--release", "--bin", "trust_module"])
        .args(["--message-format", "json"])
        .args(["--target", triple(target)]);
    if let Some(overrides) = toolchain
        .vendor
        .as_ref()
        .map(|vendor| vendor.join("build-scripts.toml"))
        .filter(|overrides| overrides.is_file())
    {
        command.arg("--config").arg(overrides);
    }
    command.env("CARGO_ENCODED_RUSTFLAGS", flags.join("\u{1f}"));
    let result = command
        .output()
        .map_err(|error| NativeError::Toolchain(format!("{}: {error}", cargo.display())))?;
    let messages = rust_messages::read(&result.stdout, &project.label);
    if !result.status.success() {
        return Err(failure(messages, &result.stderr));
    }
    Ok(messages.diagnostics)
}

/// The toolchain's `cargo`, to run in `work` as the build runs it (RU-75): in the
/// toolchain's own home, with the toolchain's compiler, its report without colour (RU-44), and with
/// none of the user's cargo settings from the environment: neither `CARGO` nor a `CARGO_`
/// variable, which cargo reads as configuration that would change what it builds (a release
/// profile's `CARGO_PROFILE_RELEASE_OVERFLOW_CHECKS`) or how it reports (`CARGO_TERM_QUIET`), and
/// none of [`USER_COMPILER_SETTINGS`].
fn cargo_command(cargo: &Path, toolchain: &Toolchain, work: &Path) -> Command {
    let mut command = Command::new(cargo);
    command.current_dir(work).args(["--color", NO_COLOUR]);
    for (name, _) in std::env::vars_os() {
        // Windows matches a variable's name in any case.
        let upper = name.to_string_lossy().to_ascii_uppercase();
        if upper == "CARGO"
            || upper.starts_with("CARGO_")
            || USER_COMPILER_SETTINGS.contains(&upper.as_str())
        {
            command.env_remove(&name);
        }
    }
    command
        .env("RUSTC", &toolchain.rustc)
        .env("CARGO_TARGET_DIR", work.join("target"))
        .env("CARGO_HOME", &toolchain.cargo_home);
    command
}

/// Refuses the scan crate graph of the package in `work` where it breaks specification 48's rules
/// (RU-09, RU-20), from cargo's metadata of it for `target`, and gives the crates of the graph that
/// the image lists, with the checksums of the package's `Cargo.lock` (RU-79).
fn check_graph(
    cargo: &Path,
    toolchain: &Toolchain,
    sdk: &Path,
    target: Target,
    work: &Path,
    project: &ProjectCrate,
) -> Result<Vec<RustCrate>, NativeError> {
    let metadata = metadata(cargo, toolchain, target, work)?;
    // The metadata names every manifest by the file system's own path.
    let crate_folder =
        std::fs::canonicalize(&project.folder).unwrap_or_else(|_| project.folder.clone());
    let errors =
        super::crate_graph::check(&metadata, sdk, &crate_folder, project.bindings.as_deref());
    if !errors.is_empty() {
        return Err(NativeError::Compile(errors.join("\n")));
    }
    let listed = super::crate_graph::audited(&metadata, &crate_folder, project.bindings.as_deref());
    let lock_path = work.join("Cargo.lock");
    let lock = std::fs::read_to_string(&lock_path)
        .map_err(|error| NativeError::Toolchain(format!("{}: {error}", lock_path.display())))?;
    super::crate_graph::image_crates(&listed, &lock).map_err(NativeError::Compile)
}

/// The crates of the scan crate graph of `project` for `target` that an advisory of the RustSec
/// database can name (specification 48 RU-79), each with its name and version: from cargo's
/// metadata of the build's package, which is written into `work` as the build writes it, with an
/// empty generated crate.
///
/// # Errors
///
/// [`NativeError::Toolchain`] when the toolchain has no cargo and SDK sources, a file cannot be
/// written, or cargo reads no metadata.
pub(super) fn graph_crates(
    toolchain: &Toolchain,
    target: Target,
    work: &Path,
    project: &ProjectCrate,
) -> Result<Vec<(String, String)>, NativeError> {
    let Package {
        cargo,
        work,
        project,
        ..
    } = write_package(toolchain, "", target, work, project)?;
    let metadata = metadata(&cargo, toolchain, target, &work)?;
    let crate_folder =
        std::fs::canonicalize(&project.folder).unwrap_or_else(|_| project.folder.clone());
    let mut crates: Vec<(String, String)> =
        super::crate_graph::audited(&metadata, &crate_folder, project.bindings.as_deref())
            .into_iter()
            .map(|entry| (entry.name, entry.version))
            .collect();
    // A name and version from two sources is one crate to the advisories.
    crates.dedup();
    Ok(crates)
}

/// Cargo's metadata of the package in `work` for `target`, read offline by the toolchain's cargo
/// as the build runs it (`cargo_command`).
fn metadata(
    cargo: &Path,
    toolchain: &Toolchain,
    target: Target,
    work: &Path,
) -> Result<serde_json::Value, NativeError> {
    let output = cargo_command(cargo, toolchain, work)
        .args(["metadata", "--offline", "--format-version", "1"])
        .args(["--filter-platform", triple(target)])
        .output()
        .map_err(|error| NativeError::Toolchain(format!("{}: {error}", cargo.display())))?;
    if !output.status.success() {
        return Err(NativeError::Toolchain(
            String::from_utf8_lossy(&output.stderr).to_string(),
        ));
    }
    serde_json::from_slice(&output.stdout)
        .map_err(|error| NativeError::Toolchain(format!("cargo metadata: {error}")))
}

