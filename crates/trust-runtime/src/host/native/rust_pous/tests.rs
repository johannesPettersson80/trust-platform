#[test]
fn the_declarations_take_only_names_structured_text_takes() {
    // RU-22 and specification 01 §3: the declarations a crate's attributes write parse and check
    // under every profile, so every name the attributes take, truST's parser and its check of
    // identifiers take at each place a Rust POU names one (a POU, a VAR variable, a parameter, a
    // structure's field, an enumeration's value) under the IEC profile, the stricter. The list of
    // reserved words is the lexer's and the check's. The check takes three reserved words the
    // attributes keep refusing, as specification 01 §3 reserves them: STEP as a VAR variable, EN and
    // ENO as parameters (IEC Table 18), pinned here (checklist G182). Catches a word the lexer or
    // the check gains that the list lacks, and a name the attributes take that a project's check
    // refuses.
    use trust_hir::db::{Database, FileId, SemanticDatabase, SourceDatabase};
    let source = |path: &str| {
        std::fs::read_to_string(std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join(path))
            .expect("a source of the language")
    };
    let lexer = source("../trust-syntax/src/lexer/tokens/token_kind.rs");
    let mut words: Vec<String> = lexer
        .split("#[token(\"")
        .skip(1)
        .filter_map(|rest| rest.split_once("\", ignore(case))]").map(|(word, _)| word))
        .filter(|word| {
            word.bytes()
                .all(|byte| byte.is_ascii_alphanumeric() || byte == b'_')
        })
        .map(str::to_string)
        .collect();
    // The check's own table, `trust_hir::ident::is_reserved_keyword`'s words.
    let ident = source("../trust-hir/src/ident.rs");
    let table = ident
        .split_once("pub fn is_reserved_keyword")
        .and_then(|(_, rest)| rest.split_once("\n}\n"))
        .map(|(body, _)| body)
        .expect("the check's table");
    words.extend(table.split('"').skip(1).step_by(2).map(str::to_string));
    words.sort_unstable();
    words.dedup();
    let mut reserved: Vec<String> = trust_plc_decl::names::RESERVED
        .iter()
        .map(|word| (*word).to_string())
        .collect();
    reserved.sort_unstable();
    assert_eq!(
        reserved, words,
        "the declarations' reserved words are the lexer's and the check's"
    );
    let places = [
        ("a POU", "FUNCTION_BLOCK {}\nEND_FUNCTION_BLOCK\n"),
        (
            "a VAR variable",
            "FUNCTION_BLOCK FB_NAMES\nVAR\n    {} : INT;\nEND_VAR\nEND_FUNCTION_BLOCK\n",
        ),
        (
            "a parameter",
            "FUNCTION_BLOCK FB_NAMES\nVAR_INPUT\n    {} : BOOL;\nEND_VAR\nEND_FUNCTION_BLOCK\n",
        ),
        (
            "a field",
            "TYPE S_NAMES :\nSTRUCT\n    {} : INT;\nEND_STRUCT\nEND_TYPE\n",
        ),
        (
            "a value",
            "TYPE E_NAMES : ({} := 0, OTHER := 1);\nEND_TYPE\n",
        ),
    ];
    let pinned = [
        ("a VAR variable", "STEP"),
        ("a parameter", "EN"),
        ("a parameter", "ENO"),
    ];
    let mut database = Database::new();
    database.set_dialect(trust_hir::Dialect::Iec);
    let mut takes = |text: String| {
        let parsed = trust_syntax::parser::parse(&text).errors().is_empty();
        database.set_source_text(FileId(0), text);
        parsed
            && !database.diagnostics(FileId(0)).iter().any(|diagnostic| {
                diagnostic.code == trust_hir::diagnostics::DiagnosticCode::InvalidIdentifier
            })
    };
    let mut differing = Vec::new();
    for word in
        words
            .iter()
            .map(String::as_str)
            .chain(["LEVEL", "Level", "REFERENCE", "_ALPHA2", "ONWARD"])
    {
        let attributes = trust_plc_decl::names::takes_name(word);
        for (place, template) in places {
            let checked = takes(template.replace("{}", word));
            let exception = pinned.contains(&(place, word));
            if attributes && !checked {
                differing.push(format!(
                    "{word} as {place}: taken by the attributes, refused by the check"
                ));
            } else if !attributes && checked && !exception {
                differing.push(format!(
                    "{word} as {place}: taken by the check, refused by the attributes"
                ));
            } else if exception && !checked {
                differing.push(format!(
                    "{word} as {place}: no longer taken by the check, no exception"
                ));
            }
        }
    }
    assert!(differing.is_empty(), "{differing:#?}");
}

#[test]
fn an_in_out_or_a_reference_the_sdk_does_not_carry_yet_is_refused() {
    // RU-29 as built so far (checklist G183): an in-out and a reference reach their variable through
    // the place of the type it has, a structure's too, so HOLDER's in-out of a structure is
    // declared. A reference's place does not hold the type it names, so an in-out of a reference,
    // a reference to one, an array of them included, and a structure's field that is a reference to
    // a reference are refused, each with its reason, as is a function's string in-out, which a
    // function takes as a view of any capacity (DEV-035). Catches a declaration whose glue could not
    // be built, with a compiler error in its place, and a structure refused that is carried now.
    let lib =
        "#![cfg_attr(not(test), no_std)]\n\npub mod modes;\npub mod geometry;\npub mod tracker;\n\
               pub mod uses;\n";
    let uses = "use trust_plc::prelude::*;\nuse crate::geometry::Point;\n\n\
                #[trust_struct(name = \"LINKED\")]\n#[derive(Clone, Copy)]\npub struct Linked {\n    \
                pub next: Ref<Ref<i16>>,\n}\n\n\
                #[trust_fb(name = \"HOLDER\")]\n#[budget(\"1us\")]\npub struct Holder {\n    \
                #[in_out] pub spot: Ref<Point>,\n    #[input] pub seen: Ref<Point>,\n}\n\n\
                #[trust_fb(name = \"CHAIN\")]\n#[budget(\"1us\")]\npub struct Chain {\n    \
                #[in_out] pub link: Ref<Ref<i16>>,\n    #[input] pub far: Ref<Array<Ref<i16>, 0, 1>>,\n}\n\n\
                #[trust_function(name = \"LABEL\")]\n#[budget(\"1us\")]\n\
                pub fn label(_cx: &mut Cx, text: InOut<'_, Str<20>>) -> Result<(), Fault> {\n    \
                let _ = text;\n    Ok(())\n}\n";
    let root = project(&[
        ("rust/Cargo.toml", MANIFEST),
        ("rust/src/lib.rs", lib),
        ("rust/src/modes.rs", MODES),
        ("rust/src/geometry.rs", GEOMETRY),
        ("rust/src/tracker.rs", TRACKER),
        ("rust/src/uses.rs", uses),
    ]);
    let found = errors(&root);
    assert!(
        !found.iter().any(|error| error.contains("HOLDER")),
        "{found:?}"
    );
    let refused = [
        (
            "LINKED",
            "the field next: a reference to a reference is not carried yet",
        ),
        (
            "CHAIN",
            "the variable link: an in-out of a reference is not carried yet",
        ),
        (
            "CHAIN",
            "the variable far: a reference to a reference is not carried yet",
        ),
        (
            "LABEL",
            "the variable text: a function's or a method's string in-out is not carried yet",
        ),
    ];
    for (pou, reason) in refused {
        assert!(
            found
                .iter()
                .any(|error| error.contains(pou) && error.contains(reason)),
            "{pou}: {reason}\n{found:?}"
        );
    }
}

/// A crate whose block AXIS has the method `jog`.
const AXIS: &str = "use trust_plc::prelude::*;

#[trust_fb(name = \"AXIS\")]
#[budget(\"1us\")]
pub struct Axis {
    #[input] pub target: f64,
}

impl Axis {
    #[trust_method]
    #[budget(\"2us\")]
    pub fn jog(&mut self, _cx: &mut Cx, distance: f64) -> Result<f64, Fault> {
        Ok(distance)
    }
}
";

#[test]
fn a_blocks_methods_are_declared_with_it() {
    // RU-32: the `#[trust_method]` functions of a block's `impl` blocks are its methods, declared
    // after its variables; a method of a type that is no `#[trust_fb]` struct, and one named as a
    // variable of its block is, are refused at their place. Catches a method left out of the
    // declarations, and one its declaration could not hold.
    let lib = "#![cfg_attr(not(test), no_std)]\n\npub mod axis;\n";
    let root = project(&[
        ("rust/Cargo.toml", MANIFEST),
        ("rust/src/lib.rs", lib),
        ("rust/src/axis.rs", AXIS),
    ]);
    let krate = read(&root).expect("the crate reads").expect("a crate");
    let text = declarations_text(&krate);
    assert!(
        text.ends_with(
            "VAR_OUTPUT\n    ENO : BOOL;\nEND_VAR\n\
             METHOD PUBLIC jog : LREAL\nVAR_INPUT\n    distance : LREAL;\nEND_VAR\nEND_METHOD\n\
             END_FUNCTION_BLOCK\n"
        ),
        "{text}"
    );
    let stray = format!(
        "{AXIS}\npub struct Other;\n\nimpl Other {{\n    #[trust_method]\n    #[budget(\"1us\")]\n    \
         pub fn run(&mut self, _cx: &mut Cx) -> Result<(), Fault> {{\n        Ok(())\n    }}\n}}\n\n\
         impl Axis {{\n    #[trust_method]\n    #[budget(\"1us\")]\n    \
         pub fn target(&mut self, _cx: &mut Cx) -> Result<(), Fault> {{\n        Ok(())\n    }}\n}}\n"
    );
    let root = project(&[
        ("rust/Cargo.toml", MANIFEST),
        ("rust/src/lib.rs", lib),
        ("rust/src/axis.rs", &stray),
    ]);
    let found = errors(&root);
    assert!(
        found
            .iter()
            .any(|error| error.contains("the method run is of `Other`, which is not one")),
        "{found:?}"
    );
    assert!(
        found.iter().any(
            |error| error.contains("the method target of AXIS is named as target of the block")
        ),
        "{found:?}"
    );
}

/// A crate whose block AIM has a method with variables and a result of the crate's types, one of
/// them named otherwise in Structured Text.
const AIM: &str = "use trust_plc::prelude::*;
use crate::modes::Mode;

#[trust_struct(name = \"S_SPOT\")]
#[derive(Clone, Copy)]
pub struct Spot {
    pub x: f64,
}

#[trust_fb(name = \"AIM\")]
#[budget(\"1us\")]
pub struct Aim {
    #[input] pub gain: f64,
}

impl Aim {
    #[trust_method]
    #[budget(\"1us\")]
    pub fn aim(&mut self, _cx: &mut Cx, spot: Spot, mode: Mode) -> Result<Spot, Fault> {
        let _ = mode;
        Ok(spot)
    }
}
";

#[test]
fn a_methods_variables_bear_the_crates_type_names_and_take_its_checks() {
    // RU-25, RU-29, RU-32: a method's variables and result of the crate's types bear their
    // Structured Text names, as the block's own variables do, and take the same checks: a type the
    // crate does not declare is refused, and so is a method's string in-out, which a method takes
    // of any capacity as a view (DEV-035), as a function does. Catches a method declared with its
    // types' Rust names, which Structured Text does not know, and a method's variable that skips
    // the checks.
    let lib = "#![cfg_attr(not(test), no_std)]\n\npub mod modes;\npub mod aim;\n";
    let root = project(&[
        ("rust/Cargo.toml", MANIFEST),
        ("rust/src/lib.rs", lib),
        ("rust/src/modes.rs", MODES),
        ("rust/src/aim.rs", AIM),
    ]);
    let krate = read(&root).expect("the crate reads").expect("a crate");
    let text = declarations_text(&krate);
    assert!(
        text.ends_with(
            "METHOD PUBLIC aim : S_SPOT\nVAR_INPUT\n    spot : S_SPOT;\n    mode : MODE;\nEND_VAR\n\
             END_METHOD\nEND_FUNCTION_BLOCK\n"
        ),
        "{text}"
    );
    let refused = format!(
        "{AIM}\nimpl Aim {{\n    #[trust_method]\n    #[budget(\"1us\")]\n    \
         pub fn tag(&mut self, _cx: &mut Cx, text: InOut<'_, Str<8>>) -> Result<(), Fault> {{\n        \
         let _ = text;\n        Ok(())\n    }}\n\n    #[trust_method]\n    #[budget(\"1us\")]\n    \
         pub fn odd(&mut self, _cx: &mut Cx, x: Unknown) -> Result<(), Fault> {{\n        \
         let _ = x;\n        Ok(())\n    }}\n}}\n"
    );
    let root = project(&[
        ("rust/Cargo.toml", MANIFEST),
        ("rust/src/lib.rs", lib),
        ("rust/src/modes.rs", MODES),
        ("rust/src/aim.rs", &refused),
    ]);
    let found = errors(&root);
    assert!(
        found.iter().any(|error| error.contains(
            "AIM: the variable text of the method tag: a function's or a method's string in-out"
        )),
        "{found:?}"
    );
    assert!(
        found.iter().any(|error| error
            .contains("AIM: the variable x of the method odd: its type `Unknown` is no")),
        "{found:?}"
    );
}
