//! A project's Rust POUs are read from its crate's sources and declared as specification 48 gives
//! (RU-06, RU-22 to RU-24). Every expected text is RU-23's or worked out by hand from it.

use std::path::{Path, PathBuf};

use super::{
    declarations_text, read, structure_paths, write_declarations, RustPou, Written,
    DECLARATIONS_FILE,
};

/// A project folder holding `files`, each a path relative to it and its text.
fn project(files: &[(&str, &str)]) -> PathBuf {
    let root = trust_test_support::unique_temp_path("rust-pous");
    for (path, text) in files {
        let file = root.join(path);
        std::fs::create_dir_all(file.parent().expect("a folder")).expect("the folder");
        std::fs::write(file, text).expect("the file");
    }
    root
}

const MANIFEST: &str = "[package]\nname = \"filling-line\"\nversion = \"0.1.0\"\nedition = \"2024\"\n\n[dependencies]\ntrust-plc = \"=0.42.0\"\n";

const LIB: &str = "#![cfg_attr(not(test), no_std)]
#![forbid(unsafe_code)]

use trust_plc::prelude::*;

pub mod filter;
mod helpers;

#[cfg(test)]
mod tests;

/// The larger of two inputs, limited to a maximum.
#[trust_function(name = \"MAX_LIMITED\")]
#[budget(\"2us\")]
pub fn max_limited(_cx: &mut Cx, a: i32, b: i32, limit: i32) -> Result<i32, Fault> {
    Ok(a.max(b).min(limit))
}
";

const FILTER: &str = "use trust_plc::prelude::*;

/// Exponential moving average of one input.
#[trust_fb(name = \"FILTER_EMA\")]
#[budget(\"15us\")]
pub struct FilterEma {
    #[input] pub x: f64,
    #[input] #[init(0.1)] pub alpha: f64,
    #[output] pub y: f64,
    primed: bool,
}
";

fn paths(pous: &[RustPou]) -> Vec<(String, Vec<String>)> {
    pous.iter()
        .map(|pou| (pou.pou.name.clone(), pou.path.clone()))
        .collect()
}

fn errors(root: &Path) -> Vec<String> {
    read(root)
        .expect_err("the crate is refused")
        .iter()
        .map(ToString::to_string)
        .collect()
}

#[test]
fn a_crates_declarations_are_its_pous_in_the_order_its_modules_declare_them() {
    // Catches a writer that misses a module's POU, reads the crate's tests (`#[cfg(test)]`, whose
    // file need not exist) or loses the place an item lies: `pub mod filter` comes before
    // MAX_LIMITED in lib.rs, and each declaration names its file (RU-23).
    let root = project(&[
        ("rust/Cargo.toml", MANIFEST),
        ("rust/src/lib.rs", LIB),
        ("rust/src/filter.rs", FILTER),
        (
            "rust/src/helpers.rs",
            "pub fn twice(x: i32) -> i32 {\n    x * 2\n}\n",
        ),
    ]);
    let krate = read(&root).expect("the crate reads").expect("a crate");
    assert_eq!(krate.name, "filling_line");
    assert_eq!(
        paths(&krate.pous),
        [
            (
                "FILTER_EMA".into(),
                vec!["filter".into(), "FilterEma".into()]
            ),
            ("MAX_LIMITED".into(), vec!["max_limited".into()]),
        ]
    );
    let places: Vec<(&str, usize)> = krate
        .pous
        .iter()
        .map(|pou| (pou.file.as_str(), pou.line))
        .collect();
    assert_eq!(places, [("rust/src/filter.rs", 6), ("rust/src/lib.rs", 15)]);
    assert_eq!(
        declarations_text(&krate),
        "(* GENERATED by trust-runtime from rust/src/filter.rs - do not edit *)\n\
         {attribute 'rust'}\n\
         FUNCTION_BLOCK FILTER_EMA\n\
         VAR_INPUT\n    x : LREAL;\n    alpha : LREAL := 0.1;\nEND_VAR\n\
         VAR_OUTPUT\n    y : LREAL;\nEND_VAR\n\
         VAR\n    primed : BOOL;\nEND_VAR\n\
         END_FUNCTION_BLOCK\n\
         \n\
         (* GENERATED by trust-runtime from rust/src/lib.rs - do not edit *)\n\
         {attribute 'rust'}\n\
         FUNCTION MAX_LIMITED : DINT\n\
         VAR_INPUT\n    a : DINT;\n    b : DINT;\n    limit : DINT;\nEND_VAR\n\
         END_FUNCTION\n"
    );
}

#[test]
fn a_pou_in_a_private_module_is_reached_through_the_roots_re_export() {
    // RU-22: the generated code calls the item from another crate, through `pub` modules or the
    // root's `pub use` of the item, under its exported name, or of its module's items.
    for (lib, expected) in [
        ("mod filter;\npub use filter::FilterEma;\n", "FilterEma"),
        ("mod filter;\npub use crate::filter::*;\n", "FilterEma"),
        (
            "mod filter;\npub use self::filter::{FilterEma as Ema};\n",
            "Ema",
        ),
    ] {
        let root = project(&[
            ("rust/Cargo.toml", MANIFEST),
            ("rust/src/lib.rs", lib),
            ("rust/src/filter.rs", FILTER),
        ]);
        let krate = read(&root).expect("the crate reads").expect("a crate");
        assert_eq!(
            paths(&krate.pous),
            [("FILTER_EMA".into(), vec![expected.to_string()])],
            "{lib}"
        );
    }
}

#[test]
fn module_files_are_found_where_the_compiler_finds_them() {
    // Catches a module file looked for in the wrong folder: `name.rs` or `name/mod.rs` beside the
    // declaring file's own modules, a child of `a/mod.rs` in `a/`, `#[path]` relative to the
    // declaring file, and an inline module's file module in its folder.
    let block = |name: &str, item: &str| {
        format!(
            "#[trust_plc::trust_fb(name = \"{name}\")]\n#[trust_plc::budget(\"1us\")]\npub struct {item};\n"
        )
    };
    let root = project(&[
        ("rust/Cargo.toml", MANIFEST),
        (
            "rust/src/lib.rs",
            "pub mod a;\n#[path = \"other/c.rs\"]\npub mod c;\npub mod d {\n    pub mod e;\n}\n",
        ),
        (
            "rust/src/a/mod.rs",
            &format!("pub mod b;\n{}", block("W", "W")),
        ),
        ("rust/src/a/b.rs", &block("X", "X")),
        ("rust/src/other/c.rs", &block("Y", "Y")),
        ("rust/src/d/e.rs", &block("Z", "Z")),
    ]);
    let krate = read(&root).expect("the crate reads").expect("a crate");
    let found: Vec<(String, String)> = krate
        .pous
        .iter()
        .map(|pou| (pou.path.join("::"), pou.file.clone()))
        .collect();
    assert_eq!(
        found,
        [
            ("a::b::X".to_string(), "rust/src/a/b.rs".to_string()),
            ("a::W".to_string(), "rust/src/a/mod.rs".to_string()),
            ("c::Y".to_string(), "rust/src/other/c.rs".to_string()),
            ("d::e::Z".to_string(), "rust/src/d/e.rs".to_string()),
        ]
    );
}

#[test]
fn what_keeps_the_declarations_from_being_written_is_named_where_it_is() {
    // Catches a writer that skips a refused item or loses its place: each error names the file,
    // the line and the column, and says what to do.
    let root = project(&[
        ("rust/Cargo.toml", MANIFEST),
        (
            "rust/src/lib.rs",
            "mod hidden;\npub mod missing;\n\n#[trust_fb(name = \"TEXT\")]\n#[budget(\"1us\")]\npub struct Text {\n    #[input] pub name: String,\n}\n\n#[trust_fb(name = \"WRONG\")]\npub fn wrong() {}\n\n#[trust_function(name = \"twice\")]\n#[budget(\"1us\")]\npub fn first(_cx: &mut Cx) -> Result<(), Fault> { Ok(()) }\n\n#[trust_function(name = \"TWICE\")]\n#[budget(\"1us\")]\npub fn second(_cx: &mut Cx) -> Result<(), Fault> { Ok(()) }\n",
        ),
        ("rust/src/hidden.rs", FILTER),
    ]);
    let found = errors(&root);
    let expected = [
        "rust/src/lib.rs:2:9: the module `missing` has no file",
        "rust/src/lib.rs:7:24: a Rust POU's variable has one of the types",
        "rust/src/lib.rs:11:8: `#[trust_fb]` declares a struct",
        "rust/src/hidden.rs:6:12: FILTER_EMA lies in the module `hidden`, which is not public",
        "rust/src/lib.rs:19:8: TWICE is declared twice: also at rust/src/lib.rs:15",
    ];
    assert_eq!(found.len(), expected.len(), "{found:#?}");
    for (error, start) in found.iter().zip(expected) {
        assert!(error.starts_with(start), "{error}\n  expected: {start}");
    }
    let broken = project(&[
        ("rust/Cargo.toml", MANIFEST),
        ("rust/src/lib.rs", "pub fn unfinished( {\n"),
    ]);
    let found = errors(&broken);
    assert_eq!(found.len(), 1, "{found:?}");
    assert!(found[0].starts_with("rust/src/lib.rs:1:"), "{found:?}");
}

#[test]
fn writing_the_declarations_writes_keeps_and_removes_the_file() {
    // RU-24: `trust-dev rust declarations` writes the crate's declarations, leaves a file that holds
    // them, and removes the file of a project that has no POU left; a project without a crate has
    // no Rust (RU-06).
    let root = project(&[
        ("rust/Cargo.toml", MANIFEST),
        ("rust/src/lib.rs", LIB),
        ("rust/src/filter.rs", FILTER),
        ("rust/src/helpers.rs", ""),
    ]);
    assert_eq!(write_declarations(&root), Ok(Written::Wrote(2)));
    let krate = read(&root).expect("the crate reads").expect("a crate");
    let written = std::fs::read_to_string(root.join(DECLARATIONS_FILE)).expect("the file");
    assert_eq!(written, declarations_text(&krate));
    assert_eq!(write_declarations(&root), Ok(Written::UpToDate));
    std::fs::remove_dir_all(root.join("rust")).expect("the crate removed");
    assert_eq!(read(&root), Ok(None));
    assert_eq!(write_declarations(&root), Ok(Written::Removed));
    assert!(!root.join(DECLARATIONS_FILE).exists());
    assert_eq!(write_declarations(&root), Ok(Written::Nothing));
}

/// An enumeration and a block whose variables are of it, in two modules.
const MODES: &str = "use trust_plc::prelude::*;

/// The modes of a pump.
#[trust_enum(name = \"MODE\")]
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Mode {
    Off = 0,
    Auto = 1,
    Manual = 5,
}
";

const PUMP: &str = "use trust_plc::prelude::*;
use crate::modes::Mode;

#[trust_fb(name = \"PUMP\")]
#[budget(\"1us\")]
pub struct Pump {
    #[input] #[init(Mode::Auto)] pub mode: Mode,
    #[output] pub modes: Array<Mode, 1, 2>,
}
";

#[test]
fn an_enumeration_is_declared_before_the_pous_and_named_by_its_variables() {
    // RU-25: the declarations write each enumeration before the POUs, and a variable of it with
    // the enumeration's Structured Text name, an array's element too, starting at the variant
    // written. Catches a type left with its Rust name, which Structured Text does not know, and an
    // enumeration declared after the POU that uses it.
    let lib = "#![cfg_attr(not(test), no_std)]\n#![forbid(unsafe_code)]\n\npub mod modes;\npub mod pump;\n";
    let root = project(&[
        ("rust/Cargo.toml", MANIFEST),
        ("rust/src/lib.rs", lib),
        ("rust/src/modes.rs", MODES),
        ("rust/src/pump.rs", PUMP),
    ]);
    let krate = read(&root).expect("the crate reads").expect("a crate");
    assert_eq!(
        declarations_text(&krate),
        "(* GENERATED by trust-runtime from rust/src/modes.rs - do not edit *)\n\
         TYPE\n    MODE : (Off := 0, Auto := 1, Manual := 5);\nEND_TYPE\n\
         \n\
         (* GENERATED by trust-runtime from rust/src/pump.rs - do not edit *)\n\
         {attribute 'rust'}\n\
         FUNCTION_BLOCK PUMP\n\
         VAR_INPUT\n    mode : MODE := Auto;\nEND_VAR\n\
         VAR_OUTPUT\n    modes : ARRAY[1..2] OF MODE;\nEND_VAR\n\
         END_FUNCTION_BLOCK\n"
    );
}

#[test]
fn a_type_or_a_variant_the_crate_does_not_declare_is_named_where_its_pou_is() {
    // RU-25: a variable's type is a type of RU-25's table or one the crate declares, and the
    // variant it starts at is one of its type's; two types or a type and a POU have one name at
    // most. Catches a declaration that Structured Text would refuse with an error far from its
    // cause.
    let lib = "#![cfg_attr(not(test), no_std)]\n\npub mod modes;\npub mod pump;\n";
    let unknown = PUMP.replace("pub mode: Mode,", "pub mode: Mood,");
    let root = project(&[
        ("rust/Cargo.toml", MANIFEST),
        ("rust/src/lib.rs", lib),
        ("rust/src/modes.rs", MODES),
        ("rust/src/pump.rs", &unknown),
    ]);
    let found = errors(&root);
    assert!(
        found.iter().any(|error| error.starts_with(
            "rust/src/pump.rs:6:1: PUMP: the variable mode: its type `Mood` is no `#[trust_enum]`"
        )),
        "{found:?}"
    );
    let wrong = PUMP.replace("Mode::Auto", "Mode::Fast");
    let root = project(&[
        ("rust/Cargo.toml", MANIFEST),
        ("rust/src/lib.rs", lib),
        ("rust/src/modes.rs", MODES),
        ("rust/src/pump.rs", &wrong),
    ]);
    let found = errors(&root);
    assert!(
        found
            .iter()
            .any(|error| error.contains("the variable mode: `Fast` is no value of MODE")),
        "{found:?}"
    );
    let clash = MODES.replace("name = \"MODE\"", "name = \"PUMP\"");
    let root = project(&[
        ("rust/Cargo.toml", MANIFEST),
        ("rust/src/lib.rs", lib),
        ("rust/src/modes.rs", &clash),
        ("rust/src/pump.rs", PUMP),
    ]);
    let found = errors(&root);
    assert!(
        found
            .iter()
            .any(|error| error.contains("PUMP is declared twice")),
        "{found:?}"
    );
}

