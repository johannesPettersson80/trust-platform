//! Where a project's Rust lies, and a Rust-first project's configuration from its `trust.toml`
//! (specification 48 RU-65 to RU-67, Appendix B). Every expected text is worked out by hand from
//! the specification.

use std::path::{Path, PathBuf};

use crate::native::rust_pous::{
    layout, read, write_generated, Layout, Written, CRATE_FOLDER, DECLARATIONS_FILE,
};

/// A project folder holding `files`, each a path relative to it and its text.
fn project(files: &[(&str, &str)]) -> PathBuf {
    let root = trust_test_support::unique_temp_path("rust-first");
    for (path, text) in files {
        let file = root.join(path);
        std::fs::create_dir_all(file.parent().expect("a folder")).expect("the folder");
        std::fs::write(file, text).expect("the file");
    }
    root
}

/// A Rust-first crate's manifest.
const MANIFEST: &str = "[package]\nname = \"cell\"\nversion = \"0.1.0\"\nedition = \"2024\"\n\n\
                        [dependencies]\ntrust-plc = \"*\"\n";

/// A Rust-first crate whose program picks parts.
const LIB: &str = "#![cfg_attr(not(test), no_std)]
#![forbid(unsafe_code)]

use trust_plc::prelude::*;

/// Closes its gripper on a part.
#[trust_program(name = \"PALLETIZER\")]
#[budget(\"5us\")]
pub struct Palletizer {
    #[input] pub part_present: bool,
    #[output] pub close_gripper: bool,
    #[output] pub count: i32,
}
";

/// Appendix B's configuration, with a second task that an event starts.
const TRUST_TOML: &str = "[rust]
crate = \".\"

[resource]
name = \"Cell\"

[tasks.Fast]
interval = \"10ms\"
priority = 1

[tasks.Kick]
event = \"Trigger\"
priority = 2

[programs.Pal1]
type = \"PALLETIZER\"
task = \"Fast\"

[globals]
LineSpeed = { type = \"REAL\", init = \"1.5\" }
Trigger = { type = \"BOOL\" }

[bindings]
\"Pal1.part_present\" = \"%IX0.0\"
\"Pal1.close_gripper\" = \"%QX0.0\"
";

fn errors(root: &Path) -> Vec<String> {
    write_generated(root)
        .expect_err("the project is refused")
        .iter()
        .map(ToString::to_string)
        .collect()
}

#[test]
fn a_project_names_where_its_crate_and_generated_text_lie() {
    // Appendix B, RU-65: without `trust.toml` the crate lies in `rust/` and its declarations in
    // `src/generated/rust_pous.st`; `crate = "."` makes the project a Rust-first one, its generated
    // Structured Text in `src/generated/trust/`, with the configuration when `[resource]` declares
    // one. A crate outside the project and a `[resource]` of a project whose crate lies in `rust/`
    // are refused with their reasons. Catches a Rust-first project's text written where the
    // Structured Text project's goes, and a configuration generated for a project that writes its
    // own.
    let plain = project(&[]);
    assert_eq!(
        layout(&plain),
        Ok(Layout {
            crate_folder: CRATE_FOLDER.to_string(),
            declarations: DECLARATIONS_FILE.to_string(),
            configuration: None,
        })
    );
    let first = project(&[("trust.toml", TRUST_TOML)]);
    assert_eq!(
        layout(&first),
        Ok(Layout {
            crate_folder: ".".to_string(),
            declarations: "src/generated/trust/rust_pous.st".to_string(),
            configuration: Some("src/generated/trust/configuration.st".to_string()),
        })
    );
    let outside = project(&[("trust.toml", "[rust]\ncrate = \"../shared\"\n")]);
    assert!(layout(&outside).is_err_and(|error| error.contains("inside the project")));
    let both = project(&[("trust.toml", "[resource]\nname = \"Cell\"\n")]);
    assert!(layout(&both).is_err_and(|error| error.contains("Rust-first project")));
}

#[test]
fn a_rust_first_projects_configuration_is_its_trust_toml() {
    // RU-66, RU-67: one CONFIGURATION named after the resource, its globals, the resource with its
    // tasks (an interval as a TIME literal, an event as SINGLE) and program instances in
    // `trust.toml`'s order, and each binding as a VAR_CONFIG entry with the type its program
    // declares; `trust-dev rust declarations` writes it beside the declarations, and the build
    // reads both. Catches a section out of `trust.toml`'s order, a binding without its type, and
    // the generated file written elsewhere.
    let root = project(&[
        ("Cargo.toml", MANIFEST),
        ("src/lib.rs", LIB),
        ("trust.toml", TRUST_TOML),
    ]);
    let written = write_generated(&root).expect("the project writes");
    assert_eq!(written, (Written::Wrote(1), Some(Written::Wrote(1))));
    let text = std::fs::read_to_string(root.join("src/generated/trust/configuration.st"))
        .expect("the configuration");
    assert_eq!(
        text,
        "(* GENERATED by trust-runtime from trust.toml - do not edit *)\n\
         CONFIGURATION Cell\n\
         VAR_GLOBAL\n    LineSpeed : REAL := 1.5;\n    Trigger : BOOL;\nEND_VAR\n\
         RESOURCE Cell ON PLC\n\
         \x20   TASK Fast (INTERVAL := T#10ms, PRIORITY := 1);\n\
         \x20   TASK Kick (SINGLE := Trigger, PRIORITY := 2);\n\
         \x20   PROGRAM Pal1 WITH Fast : PALLETIZER;\n\
         END_RESOURCE\n\
         VAR_CONFIG\n\
         \x20   Pal1.part_present AT %IX0.0 : BOOL;\n\
         \x20   Pal1.close_gripper AT %QX0.0 : BOOL;\n\
         END_VAR\n\
         END_CONFIGURATION\n"
    );
    assert!(root.join("src/generated/trust/rust_pous.st").is_file());
    assert!(!root.join(DECLARATIONS_FILE).exists());
    let krate = read(&root).expect("the crate reads").expect("a crate");
    assert_eq!(super::super::check_declarations(&root, &krate), Ok(()));
    assert_eq!(
        write_generated(&root),
        Ok((Written::UpToDate, Some(Written::UpToDate)))
    );
}

#[test]
fn a_value_trust_toml_cannot_hold_is_named() {
    // Appendix B's schema, each refusal at trust.toml with its reason: a program of no
    // `#[trust_program]`, a program on no task, a task without an interval or an event, a binding
    // to no directly represented variable, and one of no program variable. Catches a value written
    // into the configuration that the check of the project would then report in the generated file
    // instead of in trust.toml.
    let refused = |table: &str, from: &str, to: &str, reason: &str| {
        let root = project(&[
            ("Cargo.toml", MANIFEST),
            ("src/lib.rs", LIB),
            ("trust.toml", &TRUST_TOML.replace(from, to)),
        ]);
        let found = errors(&root);
        assert!(
            found
                .iter()
                .any(|error| error.starts_with("trust.toml: ") && error.contains(reason)),
            "{table}: {found:?}"
        );
    };
    refused(
        "type",
        "type = \"PALLETIZER\"",
        "type = \"PICKER\"",
        "[programs.Pal1] type \"PICKER\" names no `#[trust_program]`",
    );
    refused(
        "task",
        "task = \"Fast\"",
        "task = \"Slow\"",
        "[programs.Pal1] task \"Slow\" names no task",
    );
    refused(
        "interval",
        "interval = \"10ms\"",
        "interval = \"soon\"",
        "[tasks.Fast] interval \"soon\" is no duration",
    );
    refused(
        "address",
        "\"%IX0.0\"",
        "\"IX0.0\"",
        "[bindings] \"Pal1.part_present\" binds a directly represented variable",
    );
    refused(
        "variable",
        "\"Pal1.part_present\"",
        "\"Pal1.present\"",
        "[bindings] \"Pal1.present\" names no variable",
    );
}
