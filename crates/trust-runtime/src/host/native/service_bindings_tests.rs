//! A service's bindings (specification 48 RU-62) from the image of a program built by the test
//! harness: every expected line is worked out from the program and the specification's types.

use super::service_bindings;
use crate::harness::TestHarness;

/// A global, and a program with a variable of each kind the bindings name or leave out: elementary
/// values of several types, a structure, a block instance, an array, which holds no single value,
/// and `match`, a name Rust reserves.
const SOURCE: &str = r#"
TYPE Color : (Red, Green); END_TYPE
TYPE Point :
STRUCT
    x : REAL;
    y : REAL;
END_STRUCT;
END_TYPE

VAR_GLOBAL
    Setpoint : LREAL;
END_VAR

FUNCTION_BLOCK Valve
VAR_OUTPUT
    Open : BOOL;
END_VAR
END_FUNCTION_BLOCK

PROGRAM Main
VAR
    level : REAL;
    target : REAL;
    delay : TIME;
    name : STRING[10];
    mode : Color;
    match : INT;
    origin : Point;
    valve : Valve;
    history : ARRAY[1..3] OF INT;
END_VAR
    level := level + 1.0;
    valve();
END_PROGRAM
"#;

/// The bindings of the service recipe, which may write `Main.target`, after their header.
const BINDINGS: &str = r#"#![allow(non_snake_case, non_upper_case_globals, dead_code)]

pub const Setpoint: trust_service::Variable<f64> = trust_service::Variable::new("Setpoint");
pub mod Main {
    pub const level: trust_service::Variable<f32> = trust_service::Variable::new("Main.level");
    pub const target: trust_service::Writable<f32> = trust_service::Writable::new("Main.target");
    pub const delay: trust_service::Variable<std::time::Duration> = trust_service::Variable::new("Main.delay");
    pub const name: trust_service::Variable<String> = trust_service::Variable::new("Main.name");
    pub const mode: trust_service::Variable<String> = trust_service::Variable::new("Main.mode");
    pub const r#match: trust_service::Variable<i16> = trust_service::Variable::new("Main.match");
    pub mod origin {
        pub const x: trust_service::Variable<f32> = trust_service::Variable::new("Main.origin.x");
        pub const y: trust_service::Variable<f32> = trust_service::Variable::new("Main.origin.y");
    }
    pub mod valve {
        pub const Open: trust_service::Variable<bool> = trust_service::Variable::new("Main.valve.Open");
    }
}
"#;

#[test]
fn the_bindings_name_each_elementary_variable_with_its_rust_type() {
    // RU-62: the global as a constant of the top module, the program instance as a module, its
    // structure and its block instance as modules of their members; REAL as f32, LREAL as f64, TIME
    // as a Duration, a string and an enumeration as String, INT as i16; the array left out; `match`
    // as the raw identifier `r#match`; the writable target as a Writable. The header names the
    // command and the image's source hash. Catches a variable named after another path, a type
    // mapped to another Rust type, an array element bound, a keyword that would not compile, and a
    // write the compiler would let through to a variable outside `writes`.
    let mut harness = TestHarness::from_source(SOURCE).expect("the program compiles");
    harness.cycle();
    let state = harness
        .runtime()
        .snapshot()
        .expect("a computer keeps the program's image");
    let image = state.image();
    let text =
        service_bindings(&image, "recipe", &["Main.target".to_string()]).expect("the bindings");
    let hash: String = image
        .header()
        .source_hash
        .iter()
        .map(|byte| format!("{byte:02x}"))
        .collect();
    let header = format!(
        "// GENERATED by `trust-dev service bindings recipe` from the image of the sources with\n\
         // SHA-256 {hash}: do not edit, run the command again when the program changes\n\
         // (specification 48 RU-62).\n"
    );
    assert_eq!(text, format!("{header}{BINDINGS}"));
}

#[test]
fn a_write_the_image_holds_no_variable_for_is_refused() {
    // A `writes` path that names no member: the bindings would hand the service a handle the
    // runtime refuses. Catches bindings written against another image than the build's.
    let mut harness = TestHarness::from_source(SOURCE).expect("the program compiles");
    harness.cycle();
    let state = harness
        .runtime()
        .snapshot()
        .expect("a computer keeps the program's image");
    assert_eq!(
        service_bindings(&state.image(), "recipe", &["Main.nothing".to_string()]),
        Err("[services.recipe] writes \"Main.nothing\": Main.nothing names no member".to_string())
    );
}
