#[cfg(not(feature = "ads-wire"))]
#[test]
fn ads_add_route_cli_does_not_echo_stdin_password_when_wire_feature_is_absent() {
    let mut child = Command::new(env!("CARGO_BIN_EXE_trust-runtime"))
        .args([
            "ads",
            "add-route",
            "--route-name",
            "trust-runtime-line1",
            "--target",
            "192.168.10.5",
            "--target-net-id",
            "5.23.91.12.1.1",
            "--local-ip",
            "192.168.10.20",
            "--local-net-id",
            "192.168.10.20.1.1",
            "--password-stdin",
            "--json",
        ])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .expect("spawn trust-runtime ads add-route");
    child
        .stdin
        .as_mut()
        .expect("stdin")
        .write_all(b"super-secret-password\n")
        .expect("write stdin password");
    let output = child.wait_with_output().expect("wait add-route");

    assert_failure_contains(
        &output,
        "requires trust-runtime built with feature 'ads-wire'",
    );
    let combined = format!(
        "{}{}",
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );
    assert!(!combined.contains("super-secret-password"));
}

fn run_ads_validate(config: &Path, snapshot: &Path, generated: &Path) -> Output {
    Command::new(env!("CARGO_BIN_EXE_trust-runtime"))
        .args([
            "ads",
            "validate",
            "--offline",
            "--config",
            config.to_str().expect("config path"),
            "--snapshot",
            snapshot.to_str().expect("snapshot path"),
            "--generated",
            generated.to_str().expect("generated path"),
        ])
        .output()
        .expect("run trust-runtime ads validate")
}

fn assert_success(output: &Output) {
    assert!(
        output.status.success(),
        "expected success\nstdout:\n{}\nstderr:\n{}",
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );
}

fn assert_failure_contains(output: &Output, expected: &str) {
    assert!(
        !output.status.success(),
        "expected ads validate failure, got success\nstdout:\n{}\nstderr:\n{}",
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );
    let stderr = String::from_utf8_lossy(&output.stderr);
    assert!(
        stderr.contains(expected),
        "expected stderr to contain {expected:?}\nstdout:\n{}\nstderr:\n{}",
        String::from_utf8_lossy(&output.stdout),
        stderr
    );
}

fn write_ads_config(root: &Path) -> PathBuf {
    let path = root.join("ads.toml");
    std::fs::write(
        &path,
        r#"
[[connections]]
name = "line1"
target_net_id = "5.23.91.12.1.1"
host = "192.168.10.5"
transport = "plain"
insecure_transport = true

[[connections.points]]
symbol = "MAIN.Temperature"
var = "line1_temp"
type = "REAL"
"#,
    )
    .expect("write ads.toml");
    path
}

fn write_snapshot(root: &Path, route_name: &str, symbols: Vec<SymbolDescriptor>) -> PathBuf {
    let path = root.join("ads/snapshots/line1.symbols.json");
    std::fs::create_dir_all(path.parent().expect("snapshot parent")).expect("mkdir snapshot");
    let snapshot = SymbolSnapshot::new(route_name, symbols);
    std::fs::write(
        &path,
        snapshot.to_deterministic_json().expect("snapshot json"),
    )
    .expect("write snapshot");
    path
}

fn write_generated_source(root: &Path, source: &str) -> PathBuf {
    let path = root.join("src/generated/ads_generated.st");
    std::fs::create_dir_all(path.parent().expect("generated parent")).expect("mkdir generated");
    std::fs::write(&path, source).expect("write generated source");
    path
}

fn unique_temp_dir(prefix: &str) -> PathBuf {
    let nanos = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .expect("system time before unix epoch")
        .as_nanos();
    let counter = TEMP_COUNTER.fetch_add(1, Ordering::Relaxed);
    let root = std::env::temp_dir().join(format!(
        "trust-runtime-{prefix}-{}-{nanos}-{counter}",
        std::process::id()
    ));
    std::fs::create_dir_all(&root).expect("create temp dir");
    root
}
