#[test]
fn ads_validate_cli_returns_nonzero_with_first_diff_for_generated_drift() {
    let root = unique_temp_dir("ads-cli-source-drift");
    let config = write_ads_config(&root);
    let snapshot = write_snapshot(
        &root,
        "line1",
        vec![SymbolDescriptor::new(
            "MAIN.Temperature",
            AdsDataTypeDescriptor::scalar("REAL", IecDataType::Real),
            0x4020,
            0,
            4,
        )
        .with_flag(SymbolFlag::Read)],
    );
    let generated = write_generated_source(
        &root,
        concat!(
            "(* Generated by trust-runtime ads import-symbols. Do not edit by hand. *)\n",
            "TYPE\n",
            "    ADS_QUALITY : (Stale := 0, Good := 1, Error := 2);\n",
            "END_TYPE\n",
            "\n",
            "VAR_GLOBAL\n",
            "    (* ADS connection: line1 *)\n",
            "    (* symbol MAIN.Temperature *)\n",
            "    line1_temp : LREAL;\n",
            "    line1_temp_quality : ADS_QUALITY := Stale;\n",
            "END_VAR\n",
        ),
    );

    let output = run_ads_validate(&config, &snapshot, &generated);

    assert_failure_contains(&output, "first difference at line");
    let _ = std::fs::remove_dir_all(root);
}

